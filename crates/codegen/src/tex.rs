//! Document → LaTeX source (`.tex`) that uses the template's generated class.

use texloom_core::{Block, Document, FieldKind, FieldValue, Inline, ListItem, Mark, Template};

use crate::cls::heading_commands;
use crate::latex::{escape, escape_url};

pub fn document_to_tex(t: &Template, doc: &Document) -> String {
    let mut o = String::new();
    o.push_str(&format!("% Generated by Texloom. Uses {}.cls from the same folder.\n", t.meta.id));
    o.push_str(&format!("\\documentclass{{{}}}\n\n", t.meta.id));

    for f in &t.fields {
        let value = doc.metadata.get(&f.id).filter(|v| !v.is_empty());
        let rendered = match value {
            Some(v) => field_value(f.kind, v),
            // Show missing required fields as "[Label]" so the layout is visible.
            None if f.required => escape(&format!("[{}]", f.label)),
            None => continue,
        };
        o.push_str(&format!("\\texloomfield{{{}}}{{{rendered}}}\n", f.id));
    }

    o.push_str("\n\\begin{document}\n\\texloomfrontmatter\n\\texloommainmatter\n\n");
    let mut w = BodyWriter { out: &mut o, commands: heading_commands(t.structure.top_level) };
    w.blocks(&doc.body.content);
    o.push_str("\\end{document}\n");
    o
}

fn field_value(kind: FieldKind, v: &FieldValue) -> String {
    let items: Vec<&str> = match v {
        FieldValue::Text(s) => vec![s.as_str()],
        FieldValue::List(l) => l.iter().map(String::as_str).collect(),
    };
    match kind {
        FieldKind::Text => items.iter().map(|s| escape(s.trim())).collect::<Vec<_>>().join(", "),
        FieldKind::Paragraphs => items
            .iter()
            .flat_map(|s| s.split("\n\n"))
            .map(str::trim)
            .filter(|p| !p.is_empty())
            .map(escape)
            .collect::<Vec<_>>()
            .join("\\par "),
        FieldKind::List => items
            .iter()
            .flat_map(|s| s.lines())
            .map(str::trim)
            .filter(|s| !s.is_empty())
            .map(escape)
            .collect::<Vec<_>>()
            .join("\\texloomsep "),
    }
}

struct BodyWriter<'a> {
    out: &'a mut String,
    commands: [&'static str; 4],
}

impl BodyWriter<'_> {
    fn blocks(&mut self, blocks: &[Block]) {
        for b in blocks {
            self.block(b);
        }
    }

    fn block(&mut self, b: &Block) {
        match b {
            Block::Paragraph { content } => {
                let text = inlines(content);
                if !text.trim().is_empty() {
                    self.out.push_str(&text);
                    self.out.push_str("\n\n");
                }
            }
            Block::Heading { attrs, content } => {
                let text = inlines(content);
                if !text.trim().is_empty() {
                    let level = usize::from(attrs.level.clamp(1, 4)) - 1;
                    self.out.push_str(&format!("\\{}{{{}}}\n\n", self.commands[level], text.trim()));
                }
            }
            Block::BulletList { content } => self.list("itemize", None, content),
            Block::OrderedList { attrs, content } => {
                self.list("enumerate", Some(attrs.start).filter(|s| *s != 1), content)
            }
            Block::Blockquote { content } => {
                self.out.push_str("\\begin{quote}\n");
                self.blocks(content);
                self.out.push_str("\\end{quote}\n\n");
            }
            Block::CodeBlock { content } => {
                let code = plain_text(content).replace("\\end{verbatim}", "\\end {verbatim}");
                self.out.push_str(&format!("\\begin{{verbatim}}\n{code}\n\\end{{verbatim}}\n\n"));
            }
            Block::HorizontalRule => self.out.push_str("\\noindent\\rule{\\linewidth}{0.4pt}\n\n"),
            Block::Equation { attrs } => {
                let latex = attrs.latex.trim();
                if !latex.is_empty() {
                    self.out.push_str(&format!("\\begin{{equation}}\n{latex}\n\\end{{equation}}\n\n"));
                }
            }
            Block::Unknown => {}
        }
    }

    fn list(&mut self, env: &str, start: Option<u32>, items: &[ListItem]) {
        if items.is_empty() {
            return;
        }
        match start {
            Some(s) => self.out.push_str(&format!("\\begin{{{env}}}[start={s}]\n")),
            None => self.out.push_str(&format!("\\begin{{{env}}}\n")),
        }
        for item in items {
            let mut inner = String::new();
            BodyWriter { out: &mut inner, commands: self.commands }.blocks(&item.content);
            self.out.push_str("\\item ");
            self.out.push_str(inner.trim_end());
            self.out.push('\n');
        }
        self.out.push_str(&format!("\\end{{{env}}}\n\n"));
    }
}

fn inlines(content: &[Inline]) -> String {
    let mut s = String::new();
    for i in content {
        match i {
            Inline::Text { text, marks } => s.push_str(&apply_marks(escape(text), marks)),
            Inline::HardBreak => s.push_str("\\newline\n"),
            Inline::InlineMath { attrs } => {
                if !attrs.latex.trim().is_empty() {
                    s.push_str(&format!("${}$", attrs.latex.trim()));
                }
            }
            Inline::Unknown => {}
        }
    }
    s
}

fn apply_marks(mut text: String, marks: &[Mark]) -> String {
    for mark in marks {
        text = match mark {
            Mark::Bold => format!("\\textbf{{{text}}}"),
            Mark::Italic => format!("\\emph{{{text}}}"),
            Mark::Underline => format!("\\uline{{{text}}}"),
            Mark::Strike => format!("\\sout{{{text}}}"),
            Mark::Code => format!("\\texttt{{{text}}}"),
            Mark::Link { attrs } => format!("\\href{{{}}}{{{text}}}", escape_url(&attrs.href)),
            Mark::Unknown => text,
        };
    }
    text
}

fn plain_text(content: &[Inline]) -> String {
    content
        .iter()
        .map(|i| match i {
            Inline::Text { text, .. } => text.as_str(),
            Inline::HardBreak => "\n",
            _ => "",
        })
        .collect()
}
