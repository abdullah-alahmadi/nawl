/// Whether the document produces a reference list (it cites something and has entries).
pub fn has_bibliography(doc: &Document) -> bool {
    !doc.bibliography.trim().is_empty() && !doc.body.cited_keys().is_empty()
}

pub fn document_to_tex(t: &Template, doc: &Document) -> String {
    document_to_tex_mapped(t, doc).0
}

/// Like [`document_to_tex`], also returning the line (1-based) of the `.tex` where
/// each top-level block of the body starts, for SyncTeX (jumps between the PDF and
/// the editor).
pub fn document_to_tex_mapped(t: &Template, doc: &Document) -> (String, Vec<u32>) {
    let mut lines = vec![0u32; doc.body.content.len()];
    let mut o = String::new();
    o.push_str(&format!("% Generated by Texloom. Uses {}.cls from the same folder.\n", t.meta.id));
    if Languages::of(t, doc).main.rtl() {
        // Equation numbers at the end of the line, which is the left in Arabic. Only
        // \documentclass's options reach packages, so it's passed to amsmath here.
        o.push_str("\\PassOptionsToPackage{leqno}{amsmath}\n");
    }
    o.push_str(&format!("\\documentclass{{{}}}\n", t.meta.id));
    if has_row_spans(doc) {
        o.push_str("\\usepackage{multirow}\n");
    }
    let langs = Languages::of(t, doc);
    o.push_str(&language::preamble(t, &langs));
    o.push_str(&crate::refs::preamble(t, doc, &langs));
    if has_crops(doc) {
        o.push_str("\\usepackage{adjustbox}\n");
    }
    o.push('\n');

    for f in &t.fields {
        // Images (a logo) are used by path, not written as text: the path, for a
        // title-page image that shows the field.
        if f.kind == FieldKind::Image {
            let shown = t.placed_items().iter().any(|(_, i)| matches!(&i.content, TitleContent::Image { asset, .. } if texloom_core::image_field(asset) == Some(f.id.as_str())));
            if let Some(FieldValue::Text(p)) = doc.metadata.get(&f.id)
                && shown
                && crate::publisher::is_safe_path(p.trim())
            {
                o.push_str(&format!("\\texloomfield{{{}}}{{{}}}\n", f.id, p.trim()));
            }
            continue;
        }
        let value = doc.metadata.get(&f.id).filter(|v| !v.is_empty());
        let rendered = match value {
            // Names with their affiliations' numbers, when the authors' affiliations differ.
            Some(v) if f.kind == FieldKind::Authors && matches!(v, FieldValue::Authors(_)) => {
                let authors = texloom_core::AuthorInfo::from_field(Some(v));
                author_list(&texloom_core::author_entries(&authors, ""), false, false, &langs)
            }
            Some(v) => field_value(f.kind, v, &langs),
            // Show missing required fields as "[Label]" so the layout is visible.
            None if f.required => escape(&format!("[{}]", f.label)),
            None => continue,
        };
        o.push_str(&format!("\\texloomfield{{{}}}{{{rendered}}}\n", f.id));
        // A date's Hijri form, for {id_hijri}.
        if f.kind == FieldKind::Date
            && let Some(FieldValue::Text(v)) = value
            && let Some(hijri) = texloom_core::date::format_hijri(v, langs.main, langs.digits)
        {
            o.push_str(&format!("\\texloomfield{{{}{}}}{{{}}}\n", f.id, texloom_core::date::HIJRI_SUFFIX, language::text(&hijri, langs.main, &langs)));
        }
        // An authors field's affiliations, English names and e-mail, for title pages.
        if f.kind == FieldKind::Authors {
            let authors = texloom_core::AuthorInfo::from_field(value);
            for suffix in texloom_core::AUTHOR_SUFFIXES {
                let entries = texloom_core::author_entries(&authors, suffix);
                if entries.is_empty() {
                    continue;
                }
                // English names, affiliations, an e-mail: one English run, so a
                // right-to-left document keeps their order.
                let text = author_list(&entries, suffix != "_affiliations", suffix.starts_with("_affiliations"), &langs);
                o.push_str(&format!("\\texloomfield{{{}{suffix}}}{{{text}}}\n", f.id));
            }
        }
    }

    let presentation = t.kind == DocumentKind::Presentation;
    match &t.base {
        // Presentations: title slide from the metadata, then the slides.
        _ if presentation => {
            o.push('\n');
            o.push_str(&crate::presentation::title_slides(t, doc));
        }
        // Publisher classes: their own title block, written from the metadata.
        Some(base) => {
            let fm = crate::publisher::front_matter(t, base, doc);
            // A title block may start in the preamble (classes whose \title only works
            // there): everything above its own \begin{document} line goes before it.
            let split = fm.find("\n\\begin{document}\n").map(|i| (&fm[..i + 1], &fm[i + 17..]));
            let (pre, rest) = match split {
                Some((pre, rest)) => (pre, rest.strip_prefix('\n').unwrap_or(rest)),
                None if fm.starts_with("\\begin{document}\n") => ("", &fm[17..]),
                None => ("", fm.as_str()),
            };
            o.push('\n');
            o.push_str(pre);
            o.push_str("\\begin{document}\n");
            o.push_str(rest);
            o.push('\n');
        }
        None => o.push_str("\n\\begin{document}\n\\texloomfrontmatter\n\\texloommainmatter\n\n"),
    }
    let lang = langs.main;
    let ctx = Ctx {
        commands: heading_commands(t.structure.top_level),
        targets: doc.body.targets(),
        t,
        langs,
    };
    let mut w = BodyWriter { out: &mut o, ctx: &ctx, bibliography_pending: has_bibliography(doc), in_slide: false, in_minipage: false, lang };
    let mut counter = LineCounter::default();
    if presentation {
        w.slides(&doc.body.content, &mut counter, &mut lines);
        if std::mem::take(&mut w.bibliography_pending) {
            // The template's title for the reference list ("References", "المراجع").
            let title = escape(&t.bibliography.title);
            w.out.push_str(&format!("\\begin{{frame}}[allowframebreaks]{{{title}}}\n\\texloombibliography\n\\end{{frame}}\n\n"));
        }
        o.push_str("\\end{document}\n");
        return (o, lines);
    }
    for (i, b) in doc.body.content.iter().enumerate() {
        lines[i] = counter.next_line(w.out);
        w.block(b);
    }
    w.emit_bibliography();
    if let Some(base) = &t.base {
        o.push_str(&crate::publisher::end_matter(t, base, doc));
    }
    o.push_str("\\end{document}\n");
    (o, lines)
}

/// Counts lines of a growing string without rescanning it.
#[derive(Default)]
struct LineCounter {
    scanned: usize,
    newlines: u32,
}

impl LineCounter {
    /// The line the next text written to `s` starts on (1-based; blocks end with a
    /// newline).
    fn next_line(&mut self, s: &str) -> u32 {
        self.newlines += s[self.scanned..].matches('\n').count() as u32;
        self.scanned = s.len();
        self.newlines + 1
    }
}

fn field_value(kind: FieldKind, v: &FieldValue, langs: &Languages) -> String {
    // Escaped, with words in another script kept in their own direction.
    let escape = |s: &str| language::text(s, langs.main, langs);
    let items: Vec<&str> = match v {
        FieldValue::Text(s) => vec![s.as_str()],
        FieldValue::List(l) => l.iter().map(String::as_str).collect(),
        FieldValue::Authors(a) => a.iter().map(|a| a.name.as_str()).collect(),
    };
    match kind {
        FieldKind::Text | FieldKind::Image => items.iter().map(|s| escape(s.trim())).collect::<Vec<_>>().join(", "),
        FieldKind::Date => items.iter().map(|s| escape(&texloom_core::date::format(s, langs.main, langs.digits))).collect::<Vec<_>>().join(", "),
        FieldKind::Paragraphs => items
            .iter()
            .flat_map(|s| s.split("\n\n"))
            .map(str::trim)
            .filter(|p| !p.is_empty())
            .map(escape)
            .collect::<Vec<_>>()
            .join("\\par "),
        FieldKind::List | FieldKind::Authors => items
            .iter()
            .flat_map(|s| s.lines())
            .map(str::trim)
            .filter(|s| !s.is_empty())
            .map(escape)
            .collect::<Vec<_>>()
            .join("\\texloomsep "),
    }
}

/// Authors' names or affiliations as a list, with the numbers that pair them as
/// superscripts: after a name ("Name¹"), before an affiliation ("¹Affiliation").
/// `english` lists (an Arabic document's English names) are one English run, with
/// Western digits.
fn author_list(entries: &[(String, Option<Vec<usize>>)], english: bool, affiliations: bool, langs: &Languages) -> String {
    let arabic = !english && langs.main == Language::Arabic;
    let mark = |n: &[usize]| {
        let joined = n.iter().map(usize::to_string).collect::<Vec<_>>().join(if arabic { "،" } else { "," });
        format!("\\textsuperscript{{{}}}", if arabic { langs.local_digits(&joined) } else { joined })
    };
    let items: Vec<String> = entries
        .iter()
        .map(|(text, n)| {
            let text = if english { escape(text) } else { language::text(text, langs.main, langs) };
            match n {
                Some(n) if affiliations => format!("{}{text}", mark(n)),
                Some(n) => format!("{text}{}", mark(n)),
                None => text,
            }
        })
        .collect();
    // Numbered affiliations go one per line: each one has commas of its own.
    let numbered = affiliations && entries.iter().any(|(_, n)| n.is_some());
    if english {
        let joined = items.join(if numbered { "\\\\ " } else { "\\texloomsepen " });
        if langs.main.rtl() { format!("\\textenglish{{{joined}}}") } else { joined }
    } else {
        items.join(if numbered { "\\\\ " } else { "\\texloomsep " })
    }
}

/// What every part of the body writer needs to know.
struct Ctx<'a> {
    commands: [&'static str; 4],
    targets: HashMap<String, TargetKind>,
    t: &'a Template,
    langs: Languages,
}

/// `\label{tl:<id>}` for ids made of safe characters.
fn label(id: &Option<String>) -> String {
    match id {
        Some(id) if is_safe_id(id) => format!("\\label{{tl:{id}}}"),
        _ => String::new(),
    }
}

fn is_safe_id(id: &str) -> bool {
    !id.is_empty() && id.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
}

/// Citation keys BibTeX accepts without escaping problems.
fn is_safe_key(key: &str) -> bool {
    !key.is_empty() && key.chars().all(|c| c.is_ascii_alphanumeric() || "-_:./+".contains(c))
}

/// The word used when referring to a heading: "Chapter" from a label like
/// "Chapter {n}", or a sensible default when the label is just the number.
fn heading_word(t: &Template, level: u8, appendix: bool) -> String {
    let idx = usize::from(level.clamp(1, 4)) - 1;
    let label = if appendix && level == 1 {
        t.structure.appendix_label.as_str()
    } else {
        t.headings.levels.get(idx).map(|h| h.label.as_str()).unwrap_or("")
    };
    let word: String = label.replace("{n}", "").trim_matches(|c: char| !c.is_alphanumeric()).to_string();
    let words = crate::strings::words(t.lang().main);
    if !word.is_empty() {
        word
    } else if level == 1 && appendix {
        words.appendix.into()
    } else if level == 1 && t.structure.top_level == TopLevel::Chapter {
        words.chapter.into()
    } else {
        words.section.into()
    }
}

struct BodyWriter<'a> {
    out: &'a mut String,
    ctx: &'a Ctx<'a>,
    /// The reference list still has to be written (before appendices, or at the end).
    bibliography_pending: bool,
    /// Inside a slide (a beamer frame): headings can't be sections there.
    in_slide: bool,
    /// Inside a minipage (columns in an article): figures and tables can't float.
    in_minipage: bool,
    /// The language of the text being written (the document's, or a paragraph's own).
    lang: Language,
}

impl<'a> BodyWriter<'a> {
    /// A writer for nested content (list items, table cells) sharing the context.
    fn nested<'b>(&'b self, out: &'b mut String) -> BodyWriter<'b>
    where
        'a: 'b,
    {
        BodyWriter { out, ctx: self.ctx, bibliography_pending: false, in_slide: self.in_slide, in_minipage: self.in_minipage, lang: self.lang }
    }

    /// A presentation's body: sections between slides; anything outside a slide is
    /// put on a slide of its own so it still shows.
    /// `lines` gets the line where each block starts (loose blocks: their slide's).
    fn slides(&mut self, blocks: &[Block], counter: &mut LineCounter, lines: &mut [u32]) {
        let mut loose: Vec<&Block> = Vec::new();
        let mut loose_at: Vec<usize> = Vec::new();
        for (i, b) in blocks.iter().enumerate() {
            match b {
                Block::Slide { .. } | Block::Heading { .. } => {
                    let line = counter.next_line(self.out);
                    for j in loose_at.drain(..) {
                        lines[j] = line;
                    }
                    self.loose_slide(&mut loose);
                    lines[i] = counter.next_line(self.out);
                    self.block(b);
                }
                _ => {
                    loose.push(b);
                    loose_at.push(i);
                }
            }
        }
        let line = counter.next_line(self.out);
        for j in loose_at {
            lines[j] = line;
        }
        self.loose_slide(&mut loose);
    }

    fn loose_slide(&mut self, loose: &mut Vec<&Block>) {
        let blocks: Vec<Block> = loose.drain(..).cloned().collect();
        let mut body = String::new();
        {
            let mut w = self.nested(&mut body);
            w.in_slide = true;
            w.blocks(&blocks);
        }
        if !body.trim().is_empty() {
            let fragile = if needs_fragile(&blocks) { "[fragile]" } else { "" };
            self.out.push_str(&format!("\\begin{{frame}}{fragile}\n{}\\end{{frame}}\n\n", body));
        }
    }

    fn emit_bibliography(&mut self) {
        if std::mem::take(&mut self.bibliography_pending) {
            self.out.push_str("\\texloombibliography\n\n");
        }
    }

    fn inlines(&self, content: &[Inline]) -> String {
        let langs = &self.ctx.langs;
        if langs.english_only() {
            return content.iter().map(|i| self.inline(i)).collect();
        }
        // Words in another script than the paragraph's are wrapped as one run, also
        // across bold or italic parts ("deep \textbf{neural} networks").
        let mut pieces = Vec::new();
        let mut last = None;
        for (n, i) in content.iter().enumerate() {
            match i {
                Inline::Text { text, .. } => pieces.extend(language::split(n, text, &mut last)),
                math @ Inline::InlineMath { .. } => pieces.push(language::Piece::neutral(n, self.inline(math))),
                other => pieces.push(language::Piece::latex(n, self.inline(other))),
            }
        }
        let render = |n: usize, text: &str| match &content[n] {
            Inline::Text { marks, .. } => apply_marks(escape(text), marks),
            _ => String::new(),
        };
        language::join(&pieces, self.lang, langs, &render)
    }

    fn inline(&self, i: &Inline) -> String {
        let mut s = String::new();
        {
            match i {
                Inline::Text { text, marks } => s.push_str(&apply_marks(escape(text), marks)),
                Inline::HardBreak => s.push_str("\\newline\n"),
                Inline::InlineMath { attrs } => {
                    let latex = language::math(&clean_math(&attrs.latex), &self.ctx.langs);
                    if !latex.is_empty() {
                        s.push_str(&format!("${latex}$"));
                    }
                }
                Inline::Ref { attrs } => s.push_str(&self.reference(&attrs.target)),
                Inline::Citation { attrs } => {
                    let keys: Vec<&str> = attrs.keys.iter().map(String::as_str).filter(|k| is_safe_key(k)).collect();
                    if !keys.is_empty() {
                        let author_year = crate::refs::style_of(self.ctx.t) == BibStyle::AuthorYear;
                        let cmd = if author_year { "citep" } else { "cite" };
                        s.push_str(&format!("\\{cmd}{{{}}}", keys.join(",")));
                    }
                }
                Inline::Unknown => {}
            }
        }
        s
    }

    /// "Figure~\ref{tl:x}", "\eqref{tl:x}", "Chapter~\ref{tl:x}"…; "??" when the target is gone.
    fn reference(&self, target: &str) -> String {
        let t = self.ctx.t;
        match self.ctx.targets.get(target) {
            Some(_) if !is_safe_id(target) => "\\textbf{??}".into(),
            Some(TargetKind::Figure) => format!("{}~\\ref{{tl:{target}}}", escape(&t.captions.figure_label)),
            Some(TargetKind::Table) => format!("{}~\\ref{{tl:{target}}}", escape(&t.captions.table_label)),
            Some(TargetKind::Equation) => format!("\\eqref{{tl:{target}}}"),
            Some(TargetKind::Heading { level, appendix }) => {
                format!("{}~\\ref{{tl:{target}}}", escape(&heading_word(t, *level, *appendix)))
            }
            None => "\\textbf{??}".into(),
        }
    }

    /// Runs `f` with the text language set to `lang`.
    fn in_language<T>(&mut self, lang: Language, f: impl FnOnce(&mut Self) -> T) -> T {
        let saved = std::mem::replace(&mut self.lang, lang);
        let r = f(self);
        self.lang = saved;
        r
    }

    fn blocks(&mut self, blocks: &[Block]) {
        for b in blocks {
            self.block(b);
        }
    }

    fn block(&mut self, b: &Block) {
        match b {
            Block::Paragraph { attrs, content } => {
                let lang = self.ctx.langs.for_dir(attrs.dir, self.lang);
                let mut text = self.in_language(lang, |w| w.inlines(content));
                if lang.rtl() && text.starts_with("\\text") {
                    // A right-to-left paragraph opening with an English word or number:
                    // start the paragraph first, or it would take the word's direction.
                    text.insert_str(0, "\\leavevmode ");
                }
                if !text.trim().is_empty() {
                    if lang == self.lang {
                        self.out.push_str(&text);
                        self.out.push_str("\n\n");
                    } else {
                        // A paragraph in the other language (and direction): after a
                        // paragraph break, so it starts on a line of its own.
                        let env = lang.environment();
                        self.out.push_str(&format!("\\begin{{{env}}}\n{text}\n\\end{{{env}}}\n\n"));
                    }
                }
            }
            Block::Heading { content, .. } if self.in_slide => {
                // A heading on a slide: a bold line in the theme's structure colour.
                let text = self.inlines(content);
                if !text.trim().is_empty() {
                    self.out.push_str(&format!("{{\\usebeamercolor[fg]{{structure}}\\bfseries {}\\par}}\\smallskip\n\n", text.trim()));
                }
            }
            Block::Heading { attrs, content } if self.ctx.t.kind == DocumentKind::Presentation => {
                // Between slides: sections and subsections (the outline, the navigation).
                let text = self.inlines(content);
                if !text.trim().is_empty() {
                    let cmd = ["section", "subsection", "subsubsection", "subsubsection"][usize::from(attrs.level.clamp(1, 4)) - 1];
                    let star = if attrs.numbered { "" } else { "*" };
                    self.out.push_str(&format!("\\{cmd}{star}{{{}}}\n\n", text.trim()));
                }
            }
            Block::Heading { attrs, content } => {
                let text = self.inlines(content);
                if !text.trim().is_empty() {
                    let level = usize::from(attrs.level.clamp(1, 4)) - 1;
                    let cmd = self.ctx.commands[level];
                    let text = text.trim();
                    if attrs.numbered {
                        self.out.push_str(&format!("\\{cmd}{{{text}}}{}\n\n", label(&attrs.id)));
                    } else if self.ctx.t.base.is_some() {
                        // Publisher classes: plain starred heading ("Acknowledgment").
                        self.out.push_str(&format!("\\{cmd}*{{{text}}}\n\n"));
                    } else {
                        // Still listed in the table of contents and the running header.
                        let mark = if level < 2 { format!("\\{cmd}mark{{{text}}}") } else { String::new() };
                        self.out.push_str(&format!("\\{cmd}*{{{text}}}\\addcontentsline{{toc}}{{{cmd}}}{{{text}}}{mark}\n\n"));
                    }
                }
            }
            Block::BulletList { content } => self.list("itemize", None, content),
            Block::OrderedList { attrs, content } => {
                self.list("enumerate", Some(attrs.start).filter(|s| *s != 1), content)
            }
            Block::Blockquote { content } => {
                self.out.push_str("\\begin{quote}\n");
                self.blocks(content);
                self.out.push_str("\\end{quote}\n\n");
            }
            Block::CodeBlock { content } => {
                let code = plain_text(content).replace("\\end{verbatim}", "\\end {verbatim}");
                let verbatim = format!("\\begin{{verbatim}}\n{code}\n\\end{{verbatim}}\n");
                if self.lang.rtl() {
                    // Code reads left to right, also in an Arabic document.
                    self.out.push_str(&format!("\\begin{{english}}\n{verbatim}\\end{{english}}\n\n"));
                } else {
                    self.out.push_str(&verbatim);
                    self.out.push('\n');
                }
            }
            Block::HorizontalRule => self.out.push_str("\\noindent\\rule{\\linewidth}{0.4pt}\n\n"),
            Block::Equation { attrs } => {
                let latex = language::math(&clean_math(&attrs.latex), &self.ctx.langs);
                let latex = latex.as_str();
                if !latex.is_empty() {
                    // Multi-line equations arrive as an `aligned` block from the editor; inside
                    // `equation` they get one number for the whole block, as on screen.
                    if attrs.numbered {
                        self.out.push_str(&format!("\\begin{{equation}}{}\n{latex}\n\\end{{equation}}\n\n", label(&attrs.id)));
                    } else {
                        self.out.push_str(&format!("\\begin{{equation*}}\n{latex}\n\\end{{equation*}}\n\n"));
                    }
                }
            }
            Block::Figure { attrs, content } => {
                let (open, close) = if self.in_minipage { ("\\begin{center}\n", "\\end{center}") } else { ("\\begin{figure}[htbp]\n\\centering\n", "\\end{figure}") };
                self.out.push_str(open);
                let width = num_fraction(attrs.width_percent);
                if is_safe_relative(&attrs.src) {
                    match attrs.crop.and_then(|c| c.trim()) {
                        // Cropping: adjustbox's trim takes lengths relative to the
                        // image's own size (\width, \height), which graphicx's doesn't.
                        Some([l, b, r, t]) => self.out.push_str(&format!(
                            "\\adjincludegraphics[trim={{{l:.4}\\width}} {{{b:.4}\\height}} {{{r:.4}\\width}} {{{t:.4}\\height}},clip,width={width}\\linewidth]{{{}}}\n",
                            attrs.src
                        )),
                        None => self.out.push_str(&format!("\\includegraphics[width={width}\\linewidth]{{{}}}\n", attrs.src)),
                    }
                } else {
                    // No image chosen yet: keep the space visible.
                    let words = crate::strings::words(self.lang);
                    self.out.push_str(&format!(
                        "\\fbox{{\\parbox[c][4cm][c]{{{width}\\linewidth}}{{\\centering\\textit{{{}}}}}}}\n",
                        words.no_image
                    ));
                }
                let caption = if self.in_minipage { "\\texloomcaptionof{figure}" } else { "\\caption" };
                self.out.push_str(&format!("{caption}{{{}}}{}\n{close}\n\n", self.caption_text(content), label(&attrs.id)));
            }
            Block::TableFigure { attrs, content } => {
                let caption = content.iter().find_map(|p| match p {
                    TableFigurePart::Caption { content } => Some(self.inlines(content)),
                    _ => None,
                });
                let rows = content.iter().find_map(|p| match p {
                    TableFigurePart::Table { content } => Some(content.as_slice()),
                    _ => None,
                });
                let float = !self.in_minipage;
                self.out.push_str(if float { "\\begin{table}[htbp]\n\\centering\n" } else { "\\begin{center}\n" });
                let cmd = if float { "\\caption" } else { "\\texloomcaptionof{table}" };
                self.out.push_str(&format!("{cmd}{{{}}}{}\n", caption.unwrap_or_default().trim(), label(&attrs.id)));
                self.table(rows.unwrap_or(&[]));
                self.out.push_str(if float { "\\end{table}\n\n" } else { "\\end{center}\n\n" });
            }
            Block::Table { content } => {
                self.out.push_str("\\begin{center}\n");
                self.table(content);
                self.out.push_str("\\end{center}\n\n");
            }
            Block::AppendixStart => {
                // The reference list comes before the appendices.
                self.emit_bibliography();
                self.out.push_str("\\texloomappendix\n\n");
            }
            Block::RawLatex { attrs } => {
                let latex = attrs.latex.trim();
                if !latex.is_empty() {
                    self.out.push_str(latex);
                    self.out.push_str("\n\n");
                }
            }
            // Slides in an article (a deck opened with an article template): the title
            // as a bold line, columns as minipages, boxes as quotes, no pauses.
            Block::Slide { content, .. } if self.ctx.t.kind != DocumentKind::Presentation => {
                for b in content {
                    match b {
                        Block::SlideTitle { content } => {
                            let t = self.inlines(content);
                            if !t.trim().is_empty() {
                                self.out.push_str(&format!("\\noindent\\textbf{{{}}}\\par\\smallskip\n\n", t.trim()));
                            }
                        }
                        other => self.block(other),
                    }
                }
            }
            Block::Columns { content } if self.ctx.t.kind != DocumentKind::Presentation => {
                self.out.push_str("\\noindent\n");
                for c in content {
                    if let Block::Column { attrs, content } = c {
                        let w = num_fraction((attrs.width_percent - 2.0).max(5.0));
                        self.out.push_str(&format!("\\begin{{minipage}}[t]{{{w}\\linewidth}}\n"));
                        let was = std::mem::replace(&mut self.in_minipage, true);
                        self.blocks(content);
                        self.in_minipage = was;
                        self.out.push_str("\\end{minipage}\\hfill\n");
                    }
                }
                self.out.push_str("\n");
            }
            Block::SlideBox { attrs, content } if self.ctx.t.kind != DocumentKind::Presentation => {
                self.out.push_str("\\begin{quote}\n");
                if !attrs.title.trim().is_empty() {
                    self.out.push_str(&format!("\\textbf{{{}}}\\par\n", escape(attrs.title.trim())));
                }
                self.blocks(content);
                self.out.push_str("\\end{quote}\n\n");
            }
            Block::SlidePause if self.ctx.t.kind != DocumentKind::Presentation => {}
            Block::Slide { attrs, content } => {
                let title = content.iter().find_map(|b| match b {
                    Block::SlideTitle { content } => Some(self.inlines(content).trim().to_string()),
                    _ => None,
                });
                let body_blocks: Vec<Block> = content.iter().filter(|b| !matches!(b, Block::SlideTitle { .. })).cloned().collect();
                let mut body = String::new();
                {
                    let mut w = self.nested(&mut body);
                    w.in_slide = true;
                    w.blocks(&body_blocks);
                }
                let mut opts = Vec::new();
                if needs_fragile(&body_blocks) {
                    opts.push("fragile");
                }
                if attrs.plain {
                    opts.push("plain");
                }
                let opts = if opts.is_empty() { String::new() } else { format!("[{}]", opts.join(",")) };
                let title = match title {
                    Some(t) if !t.is_empty() => format!("{{{t}}}"),
                    _ => String::new(),
                };
                self.out.push_str(&format!("\\begin{{frame}}{opts}{title}{}\n{body}\\end{{frame}}\n\n", label(&attrs.id)));
            }
            Block::SlideTitle { .. } => {}
            Block::Columns { content } => {
                self.out.push_str("\\begin{columns}[T]\n");
                for c in content {
                    if let Block::Column { attrs, content } = c {
                        self.out.push_str(&format!("\\begin{{column}}{{{}\\textwidth}}\n", num_fraction(attrs.width_percent)));
                        self.blocks(content);
                        self.out.push_str("\\end{column}\n");
                    }
                }
                self.out.push_str("\\end{columns}\n\n");
            }
            Block::Column { content, .. } => self.blocks(content),
            Block::SlideBox { attrs, content } => {
                let env = match attrs.kind {
                    SlideBoxKind::Block => "block",
                    SlideBoxKind::Alert => "alertblock",
                    SlideBoxKind::Example => "exampleblock",
                };
                self.out.push_str(&format!("\\begin{{{env}}}{{{}}}\n", escape(attrs.title.trim())));
                self.blocks(content);
                self.out.push_str(&format!("\\end{{{env}}}\n\n"));
            }
            Block::SlidePause => self.out.push_str("\\pause\n\n"),
            Block::Unknown => {}
        }
    }

    fn caption_text(&self, content: &[Caption]) -> String {
        content.iter().map(|c| self.inlines(&c.content)).collect::<Vec<_>>().join(" ").trim().to_string()
    }

    /// A grid table that always fits the text width; long cell text wraps. Cells can
    /// span columns (`\multicolumn`) and rows (`\multirow`; the rows below leave
    /// their place empty and the rule under the spanned rows skips it).
    fn table(&mut self, rows: &[TableRow]) {
        let grid = TableGrid::new(rows);
        let columns = grid.columns;
        if columns == 0 {
            return;
        }
        // Plain tabular with equal p columns where tabularx can't be used (REVTeX).
        let plain = self.ctx.t.base.as_ref().is_some_and(crate::publisher::uses_plain_tables);
        if plain {
            let width = format!("\\dimexpr(\\linewidth-{}\\tabcolsep-{}\\arrayrulewidth)/{columns}\\relax", 2 * columns, columns + 1);
            self.out.push_str(&format!("\\begin{{tabular}}{{|{}}}\n\\hline\n", format!("p{{{width}}}|").repeat(columns)));
        } else {
            self.out.push_str(&format!("\\begin{{tabularx}}{{\\linewidth}}{{|{}}}\n\\hline\n", "L|".repeat(columns)));
        }
        // A spanned cell's column spec: the left rule only in the first column.
        let multicolumn = |col: usize, span: usize, text: &str| format!("\\multicolumn{{{span}}}{{{}l|}}{{{text}}}", if col == 0 { "|" } else { "" });
        for r in 0..rows.len() {
            let mut cells = Vec::new();
            let mut col = 0;
            while col < columns {
                let Some(i) = grid.at(r, col) else {
                    // Short rows get empty cells so every row has the same number of columns.
                    cells.push(String::new());
                    col += 1;
                    continue;
                };
                let p = &grid.placed[i];
                if p.row < r {
                    // Covered by a cell spanning down from above.
                    cells.push(if p.colspan > 1 { multicolumn(col, p.colspan, "") } else { String::new() });
                    col += p.colspan;
                    continue;
                }
                let cell = &rows[p.row].content[p.index];
                let mut inner = String::new();
                self.nested(&mut inner).blocks(&cell.content);
                let mut text = inner.trim().replace("\n\n", "\\par ");
                if cell.is_header() && !text.is_empty() {
                    text = format!("{{\\bfseries {text}}}");
                }
                if p.rowspan > 1 {
                    // "=": the column's width, so the text wraps (not inside \multicolumn{…}{l}).
                    let width = if p.colspan > 1 { "*" } else { "=" };
                    text = format!("\\multirow{{{}}}{{{width}}}{{{text}}}", p.rowspan);
                } else if plain && p.colspan == 1 && !text.is_empty() {
                    text = format!("\\raggedright {text}");
                }
                cells.push(if p.colspan > 1 { multicolumn(col, p.colspan, &text) } else { text });
                col += p.colspan;
            }
            self.out.push_str(&cells.join(" & "));
            // \tabularnewline: a \\ after \raggedright would end the paragraph instead.
            self.out.push_str(if plain { " \\tabularnewline " } else { " \\\\ " });
            self.out.push_str(&grid.rule_below(r));
            self.out.push('\n');
        }
        self.out.push_str(if plain { "\\end{tabular}\n" } else { "\\end{tabularx}\n" });
    }

    fn list(&mut self, env: &str, start: Option<u32>, items: &[ListItem]) {
        if items.is_empty() {
            return;
        }
        self.out.push_str(&format!("\\begin{{{env}}}\n"));
        // Works without enumitem, which some publisher classes don't get along with.
        if let Some(s) = start {
            self.out.push_str(&format!("\\setcounter{{enumi}}{{{}}}\n", s.saturating_sub(1)));
        }
        for item in items {
            let mut inner = String::new();
            self.nested(&mut inner).blocks(&item.content);
            self.out.push_str("\\item ");
            self.out.push_str(inner.trim_end());
            self.out.push('\n');
        }
        self.out.push_str(&format!("\\end{{{env}}}\n\n"));
    }
}

/// `0.8` for 80 %, clamped to a sensible range.
/// Verbatim code on a slide needs beamer's `fragile` frame option.
/// A table cell's place on the grid.
struct PlacedCell {
    row: usize,
    /// Index in its row's cells.
    index: usize,
    colspan: usize,
    rowspan: usize,
}

/// Where each cell of a table sits, like an HTML table: a cell spanning rows takes
/// its columns in the rows below, whose cells move right past it.
struct TableGrid {
    placed: Vec<PlacedCell>,
    /// For each row and column, the cell covering it.
    slots: Vec<Vec<Option<usize>>>,
    columns: usize,
}

impl TableGrid {
    fn new(rows: &[TableRow]) -> Self {
        let mut slots: Vec<Vec<Option<usize>>> = vec![Vec::new(); rows.len()];
        let mut placed = Vec::new();
        for (r, row) in rows.iter().enumerate() {
            let mut col = 0;
            for (index, cell) in row.content.iter().enumerate() {
                while slots[r].get(col).is_some_and(Option::is_some) {
                    col += 1;
                }
                let colspan = cell.attrs.colspan.max(1) as usize;
                let rowspan = (cell.attrs.rowspan.max(1) as usize).min(rows.len() - r);
                for line in &mut slots[r..r + rowspan] {
                    if line.len() < col + colspan {
                        line.resize(col + colspan, None);
                    }
                    for slot in &mut line[col..col + colspan] {
                        *slot = Some(placed.len());
                    }
                }
                placed.push(PlacedCell { row: r, index, colspan, rowspan });
                col += colspan;
            }
        }
        let columns = slots.iter().map(Vec::len).max().unwrap_or(0);
        Self { placed, slots, columns }
    }

    fn at(&self, row: usize, col: usize) -> Option<usize> {
        self.slots[row].get(col).copied().flatten()
    }

    /// `\hline`, or `\cline`s that leave out cells spanning on into the next row.
    fn rule_below(&self, row: usize) -> String {
        let continues = |col: usize| self.at(row, col).is_some_and(|i| self.placed[i].row + self.placed[i].rowspan > row + 1);
        if !(0..self.columns).any(continues) {
            return "\\hline".into();
        }
        let mut out = String::new();
        let mut col = 0;
        while col < self.columns {
            if continues(col) {
                col += 1;
                continue;
            }
            let start = col;
            while col < self.columns && !continues(col) {
                col += 1;
            }
            out.push_str(&format!("\\cline{{{}-{}}}", start + 1, col));
        }
        out
    }
}

/// The document has a cropped image (it needs adjustbox).
fn has_crops(doc: &Document) -> bool {
    let mut found = false;
    walk_blocks(&doc.body.content, &mut |b| {
        found |= matches!(b, Block::Figure { attrs, .. } if attrs.crop.and_then(|c| c.trim()).is_some());
    });
    found
}

/// The document has a table cell spanning rows (it needs the multirow package).
fn has_row_spans(doc: &Document) -> bool {
    let mut found = false;
    walk_blocks(&doc.body.content, &mut |b| {
        let spans = |rows: &[TableRow]| rows.iter().flat_map(|r| &r.content).any(|c| c.attrs.rowspan > 1);
        match b {
            Block::Table { content } => found |= spans(content),
            Block::TableFigure { content, .. } => {
                found |= content.iter().any(|part| matches!(part, TableFigurePart::Table { content } if spans(content)))
            }
            _ => {}
        }
    });
    found
}

fn needs_fragile(blocks: &[Block]) -> bool {
    let mut found = false;
    walk_blocks(blocks, &mut |b| found |= matches!(b, Block::CodeBlock { .. }));
    found
}

fn num_fraction(percent: f32) -> String {
    let f = (percent.clamp(5.0, 100.0) / 100.0 * 100.0).round() / 100.0;
    crate::latex::num(f)
}

/// Image paths must stay inside the document's folder.
fn is_safe_relative(path: &str) -> bool {
    !path.is_empty()
        && !path.starts_with('/')
        && !path.contains('\\')
        && path.split('/').all(|s| !s.is_empty() && s != "..")
        && !path.chars().any(|c| matches!(c, '{' | '}' | '%' | '#' | '$' | '&' | '~' | '^'))
}

/// MathLive marks empty cells with `\placeholder{…}`, which isn't LaTeX: keep what's
/// inside (usually nothing).
fn clean_math(latex: &str) -> String {
    let mut out = String::with_capacity(latex.len());
    let mut rest = latex;
    while let Some(i) = rest.find("\\placeholder{") {
        out.push_str(&rest[..i]);
        rest = &rest[i + "\\placeholder{".len()..];
        let mut depth = 1;
        let mut end = rest.len();
        for (j, c) in rest.char_indices() {
            match c {
                '{' => depth += 1,
                '}' => {
                    depth -= 1;
                    if depth == 0 {
                        end = j;
                        break;
                    }
                }
                _ => {}
            }
        }
        out.push_str(&rest[..end]);
        rest = rest.get(end + 1..).unwrap_or("");
    }
    out.push_str(rest);
    out.trim().to_string()
}

fn apply_marks(mut text: String, marks: &[Mark]) -> String {
    for mark in marks {
        text = match mark {
            Mark::Bold => format!("\\textbf{{{text}}}"),
            Mark::Italic => format!("\\emph{{{text}}}"),
            Mark::Underline => format!("\\uline{{{text}}}"),
            Mark::Strike => format!("\\sout{{{text}}}"),
            Mark::Code => format!("\\texttt{{{text}}}"),
            Mark::Link { attrs } => format!("\\href{{{}}}{{{text}}}", escape_url(&attrs.href)),
            Mark::Unknown => text,
        };
    }
    text
}

fn plain_text(content: &[Inline]) -> String {
    content
        .iter()
        .map(|i| match i {
            Inline::Text { text, .. } => text.as_str(),
            Inline::HardBreak => "\n",
            _ => "",
        })
        .collect()
}
