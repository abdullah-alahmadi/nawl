/// The wrapper class: loads the publisher class and adds what Nawl documents use.
/// Classes whose tables avoid the array package (see [`wrapper_cls`]).
pub fn uses_plain_tables(base: &ClassBase) -> bool {
    // jmlr refuses tabularx outright (it breaks its footnote links); the OUP class
    // breaks its X columns.
    // AASTeX is built on REVTeX.
    base.class.starts_with("revtex")
        || base.class.starts_with("aastex")
        || ["jmlr", "oup-authoring-template"].contains(&base.class.as_str())
}

pub fn wrapper_cls(t: &Template, base: &ClassBase, engine: Engine) -> String {
    let mut o = String::new();
    let id = &t.meta.id;
    let one_line = |s: &str| s.replace(['\n', '\r'], " ");
    w!(o, "% {id}.cls — generated by Nawl from the template \"{}\" (v{}).", one_line(&t.meta.name), one_line(&t.meta.version));
    w!(o, "% Built on the publisher class {}; layout, fonts and captions come from it.", base.class);
    w!(o, "\\NeedsTeXFormat{{LaTeX2e}}");
    // No "[date version]" text: LaTeX parses its start as a date, and some classes
    // (IEEEtran in journal mode) compare it, failing on anything else.
    w!(o, "\\ProvidesClass{{{id}}}");
    // Kits with their own fonts load font maps only under pdfTeX (\ifpdf); under
    // XeTeX the PDF writer gets them here instead, when the first page starts.
    let maps: Vec<&str> = base
        .files
        .iter()
        .map(|f| f.rsplit('/').next().unwrap_or(f))
        .filter(|f| f.ends_with(".map"))
        .collect();
    if !maps.is_empty() && engine == Engine::Xe {
        let specials: String = maps.iter().map(|m| format!("\\special{{pdf:mapfile {m}}}")).collect();
        w!(o, "\\AtBeginDvi{{{specials}}}");
    }
    // Kit classes are copied next to the document, so only the file name matters.
    let class = base.class.trim_end_matches(".cls").rsplit('/').next().unwrap_or(&base.class);
    w!(o, "\\LoadClass[{}]{{{class}}}", base.options.join(","));
    w!(o);

    let acm = base.front_matter == FrontMatterStyle::Acm;
    w!(o, "% Packages Nawl documents use");
    w!(o, "\\RequirePackage{{graphicx}}");
    w!(o, "\\RequirePackage{{amsmath}}");
    if !acm {
        // acmart's math fonts already provide these symbols (and clash with amssymb),
        // as do classes loading newtx and the like: \Bbbk is defined then.
        w!(o, "\\ifdefined\\Bbbk\\else\\RequirePackage{{amssymb}}\\fi");
    }
    // REVTeX 4.2 breaks with the array package of current TeX distributions
    // ("Extra \or"), so its tables use plain p columns instead of tabularx.
    if !uses_plain_tables(base) {
        w!(o, "\\RequirePackage{{tabularx}}");
        // Right-to-left text starts at the right.
        let ragged = if t.lang().main.rtl() { "raggedleft" } else { "raggedright" };
        w!(o, "\\newcolumntype{{L}}{{>{{\\{ragged}\\arraybackslash}}X}}");
    }
    w!(o, "\\RequirePackage[normalem]{{ulem}}");
    w!(o);

    if acm {
        w!(o, "% Drafts: no ACM rights block or reference format (ACM supplies these on acceptance).");
        w!(o, "\\setcopyright{{none}}");
        w!(o, "\\settopmatter{{printacmref=false}}");
        w!(o, "\\renewcommand\\footnotetextcopyrightpermission[1]{{}}");
        w!(o);
    }

    w!(o, "% Metadata fields");
    w!(o, "\\newcommand\\texloomfield[2]{{\\expandafter\\def\\csname tl@f@#1\\endcsname{{#2}}}}");
    w!(o, "\\newcommand\\tl@f[1]{{\\ifcsname tl@f@#1\\endcsname\\csname tl@f@#1\\endcsname\\fi}}");
    w!(o, "\\newcommand\\texloomsep{{, }}");
    // Between authors: \and where the class sets authors in a tabular (standard
    // \maketitle), a comma where it doesn't (\and breaks outside a tabular).
    // (An Arabic comma in Arabic documents.)
    let comma = if t.lang().main.rtl() { "،" } else { "," };
    w!(o, "\\DeclareRobustCommand\\texloomand{{\\ifx\\\\\\@tabularcr\\and\\else\\unskip{comma}\\ \\fi}}");
    w!(o);
    w!(o, "% Bibliography (refs.bib next to the document) and appendices");
    // Classes that load biblatex themselves get its commands instead of BibTeX's.
    w!(o, "\\@ifpackageloaded{{biblatex}}{{\\addbibresource{{refs.bib}}\\newcommand\\texloombibliography{{\\printbibliography}}}}");
    let style = match base.bib_style.trim() {
        "" => String::new(),
        s => format!("\\bibliographystyle{{{s}}}"),
    };
    w!(o, "  {{\\newcommand\\texloombibliography{{{style}\\bibliography{{refs}}}}}}");
    if crate::refs::style_of(t) == nawl_core::BibStyle::AuthorYear {
        // Author-year citations ("(Smith, 2021)") on a standard class need natbib.
        w!(o, "\\@ifpackageloaded{{natbib}}{{}}{{\\RequirePackage[round]{{natbib}}}}");
    }
    w!(o, "\\newcommand\\texloomappendix{{\\appendix}}");
    // Book classes have no abstract environment: a simple one, like article's.
    w!(o, "\\@ifundefined{{abstract}}{{\\providecommand\\abstractname{{{}}}%", crate::strings::words(t.lang().main).abstract_name);
    w!(o, "  \\newenvironment{{abstract}}{{\\begin{{center}}\\bfseries\\abstractname\\end{{center}}\\begin{{quote}}}}{{\\end{{quote}}}}}}{{}}");
    w!(o, "% A caption outside a float (figures and tables inside columns)");
    w!(o, "\\newcommand\\texloomcaptionof[2]{{\\def\\@captype{{#1}}\\caption{{#2}}}}");
    w!(o);
    if acm {
        // acmart loads hyperref itself, with its own settings.
        w!(o, "\\RequirePackage{{hyperref}}");
    } else {
        let raw = t.raw_preamble.as_deref().is_some_and(|r| !r.trim().is_empty());
        // Some classes load hyperref themselves, with their own options, possibly as
        // late as \begin{document} (lni); loading it first would be an option clash.
        // So it is loaded at \\begin{document} (before classes' end-of-preamble code,
        // which may load cleveref), unless the template's raw preamble may need it.
        w!(o, "\\PassOptionsToPackage{{hidelinks}}{{hyperref}}");
        let load = "\\@ifpackageloaded{hyperref}{\\hypersetup{hidelinks}}{\\RequirePackage{hyperref}}";
        if raw {
            w!(o, "{load}");
        } else {
            w!(o, "\\AddToHook{{env/document/begin}}{{{load}}}");
        }
    }
    if let Some(raw) = t.raw_preamble.as_deref().filter(|r| !r.trim().is_empty()) {
        w!(o);
        w!(o, "% Raw preamble from the template");
        w!(o, "{}", raw.trim_end());
    }
    w!(o, "\\endinput");
    o
}

// ---------------------------------------------------------------- document data

/// Escapes metadata text, keeping words in another script than the document's
/// (English words in an Arabic title) in their own direction.
fn text_escaper(t: &Template, doc: &Document) -> impl Fn(&str) -> String {
    let langs = crate::language::Languages::of(t, doc);
    let main = langs.main;
    move |s: &str| crate::language::text(s, main, &langs)
}

pub(crate) fn field_text(doc: &Document, t: &Template, id: &str) -> String {
    let escape = text_escaper(t, doc);
    match doc.metadata.get(id).filter(|v| !v.is_empty()) {
        Some(FieldValue::Text(s)) => escape(s.trim()),
        Some(FieldValue::List(l)) => escape(&l.join(", ")),
        Some(FieldValue::Authors(a)) => escape(&a.iter().map(|a| a.name.as_str()).collect::<Vec<_>>().join(", ")),
        None => t
            .field(id)
            .filter(|f| f.required)
            .map(|f| escape(&format!("[{}]", f.label)))
            .unwrap_or_default(),
    }
}

fn paragraphs(doc: &Document, t: &Template, id: &str) -> String {
    let escape = text_escaper(t, doc);
    match doc.metadata.get(id).filter(|v| !v.is_empty()) {
        Some(FieldValue::Text(s)) => {
            s.split("\n\n").map(str::trim).filter(|p| !p.is_empty()).map(&escape).collect::<Vec<_>>().join("\n\n")
        }
        Some(FieldValue::List(l)) => l.iter().map(|p| escape(p.trim())).collect::<Vec<_>>().join("\n\n"),
        _ => field_text(doc, t, id),
    }
}

fn keywords(doc: &Document) -> Vec<String> {
    let raw = match doc.metadata.get("keywords") {
        Some(FieldValue::Text(s)) => s.clone(),
        Some(FieldValue::List(l)) => l.join(","),
        _ => String::new(),
    };
    raw.split([',', ';', '\n']).map(str::trim).filter(|k| !k.is_empty()).map(escape).collect()
}

/// Paragraphs of free text (a biography): blank lines separate paragraphs.
fn bio_text(s: &str) -> String {
    s.split("\n\n").map(str::trim).filter(|p| !p.is_empty()).map(escape).collect::<Vec<_>>().join("\n\n")
}

/// Authors with their affiliations numbered in order of first appearance.
pub struct Authors {
    pub list: Vec<AuthorInfo>,
    /// Unique affiliations, in order.
    pub affiliations: Vec<String>,
    /// For each author, 1-based indexes into `affiliations`.
    pub numbers: Vec<Vec<usize>>,
}

impl Authors {
    pub fn new(doc: &Document) -> Self {
        let list = AuthorInfo::from_field(doc.metadata.get("authors"));
        let mut affiliations: Vec<String> = Vec::new();
        let numbers = list
            .iter()
            .map(|a| {
                a.affiliations
                    .iter()
                    .map(|aff| match affiliations.iter().position(|x| x == aff) {
                        Some(i) => i + 1,
                        None => {
                            affiliations.push(aff.clone());
                            affiliations.len()
                        }
                    })
                    .collect()
            })
            .collect();
        Self { list, affiliations, numbers }
    }

    /// Authors whose *first* affiliation is number `n`.
    fn first_at(&self, n: usize) -> impl Iterator<Item = &AuthorInfo> {
        self.list.iter().zip(&self.numbers).filter(move |(_, nums)| nums.first() == Some(&n)).map(|(a, _)| a)
    }

    fn corresponding(&self) -> Option<&AuthorInfo> {
        self.list.iter().find(|a| a.corresponding)
    }
}

/// "A", "A and B", "A, B, and C" (or with another final word, e.g. "AND").
fn join_names(names: &[String], and: &str) -> String {
    match names {
        [] => String::new(),
        [a] => a.clone(),
        [a, b] => format!("{a} {and} {b}"),
        [rest @ .., last] => format!("{}, {and} {last}", rest.join(", ")),
    }
}

fn nums(n: &[usize]) -> String {
    n.iter().map(usize::to_string).collect::<Vec<_>>().join(",")
}

