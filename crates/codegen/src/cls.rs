//! Template → LaTeX class (`.cls`).
//!
//! The class is self-contained and usable outside Texloom: a document sets metadata
//! with `\texloomfield{id}{value}`, then calls `\texloomfrontmatter` and
//! `\texloommainmatter`. Package mapping: geometry (page), fontspec (fonts), setspace
//! (line spacing), titlesec (headings), fancyhdr + lastpage (headers/footers),
//! TikZ overlay (title page), hyperref (links).

use std::fmt::Write;

use texloom_core::{
    Anchor, BuiltinFont, FontChoice, FrontMatterItem, HeadingLayout, LineSpacing, PageNumberStyle,
    PageStyle, Paper, Template, TitleContent, TopLevel,
};

use crate::latex::{align_name, escape, font_commands, num, render_placeholders, PlaceholderContext};

/// Heading commands for editor levels 1–4.
pub fn heading_commands(top: TopLevel) -> [&'static str; 4] {
    match top {
        TopLevel::Chapter => ["chapter", "section", "subsection", "subsubsection"],
        TopLevel::Section => ["section", "subsection", "subsubsection", "paragraph"],
    }
}

/// Writes formatted lines into a `String` (writing to a String can't fail).
macro_rules! w {
    ($o:expr) => { $o.push('\n') };
    ($o:expr, $($arg:tt)*) => { writeln!($o, $($arg)*).expect("write to String") };
}

pub fn template_to_cls(t: &Template) -> String {
    let mut o = String::new();
    let id = &t.meta.id;
    let one_line = |s: &str| s.replace(['\n', '\r'], " ");
    let chapters = t.structure.top_level == TopLevel::Chapter;

    // ---- identification
    w!(o, "% {id}.cls — generated by Texloom from the template \"{}\" (v{}).", one_line(&t.meta.name), one_line(&t.meta.version));
    w!(o, "% Edit the template in Texloom instead of this file: it is regenerated.");
    w!(o, "%");
    w!(o, "% Usage:");
    w!(o, "%   \\documentclass{{{id}}}");
    for f in &t.fields {
        w!(o, "%   \\texloomfield{{{}}}{{...}}   % {}", f.id, one_line(&f.label));
    }
    w!(o, "%   \\begin{{document}}");
    w!(o, "%   \\texloomfrontmatter");
    w!(o, "%   \\texloommainmatter");
    w!(o, "%   ...");
    w!(o, "%   \\end{{document}}");
    w!(o, "% List fields separate entries with \\texloomsep.");
    w!(o, "\\NeedsTeXFormat{{LaTeX2e}}");
    w!(o, "\\ProvidesClass{{{id}}}[v{} Texloom template: {}]", escape(&t.meta.version), escape(&t.meta.name));
    w!(o);

    // ---- base class
    let base = if chapters { "report" } else { "article" };
    let sides = if t.page.two_sided { "twoside" } else { "oneside" };
    let extra = if chapters { ",openany" } else { "" };
    w!(o, "\\LoadClass[{}pt,{sides}{extra}]{{{base}}}", t.fonts.base_size_pt);
    w!(o);

    // ---- page geometry
    let (pw, ph) = t.page.paper.size_mm();
    let paper = match t.page.paper {
        Paper::A4 => "a4paper".to_string(),
        Paper::A5 => "a5paper".to_string(),
        Paper::Letter => "letterpaper".to_string(),
        Paper::Legal => "legalpaper".to_string(),
        Paper::Custom { .. } => format!("paperwidth={}mm,paperheight={}mm", num(pw), num(ph)),
    };
    let m = &t.page.margins;
    w!(o, "% Page");
    w!(
        o,
        "\\RequirePackage[{paper},top={}mm,bottom={}mm,inner={}mm,outer={}mm,bindingoffset={}mm,headheight=15pt]{{geometry}}",
        num(m.top_mm),
        num(m.bottom_mm),
        num(m.inner_mm),
        num(m.outer_mm),
        num(t.page.binding_offset_mm)
    );
    w!(o, "\\RequirePackage{{setspace}}");
    match t.page.line_spacing {
        LineSpacing::Single => w!(o, "\\singlespacing"),
        LineSpacing::OneHalf => w!(o, "\\onehalfspacing"),
        LineSpacing::Double => w!(o, "\\doublespacing"),
        LineSpacing::Custom { stretch } => w!(o, "\\setstretch{{{}}}", num(stretch)),
    }
    // Same space after every period ("Dr. Lopez"), as in modern typography.
    w!(o, "\\frenchspacing");
    w!(o, "\\setlength{{\\parindent}}{{{}mm}}", num(t.page.paragraph.indent_mm));
    w!(o, "\\setlength{{\\parskip}}{{{}pt plus 1pt}}", num(t.page.paragraph.spacing_pt));
    w!(o);

    // ---- fonts
    w!(o, "% Fonts");
    w!(o, "\\RequirePackage{{fontspec}}");
    for (cmd, choice) in [("setmainfont", &t.fonts.main), ("setsansfont", &t.fonts.sans), ("setmonofont", &t.fonts.mono)] {
        if let Some(line) = font_line(cmd, choice) {
            w!(o, "{line}");
        }
    }
    w!(o);

    // ---- packages used by document content
    w!(o, "% Content");
    w!(o, "\\RequirePackage{{amsmath,amssymb}}");
    w!(o, "\\RequirePackage{{graphicx}}");
    w!(o, "\\RequirePackage{{xcolor}}");
    w!(o, "\\RequirePackage{{tikz}}");
    w!(o, "\\RequirePackage[normalem]{{ulem}}");
    w!(o, "\\RequirePackage{{enumitem}}");
    w!(o, "\\RequirePackage{{lastpage}}");
    w!(o);

    // ---- numbering
    let cmds = heading_commands(t.structure.top_level);
    let depth = |d: u8| if chapters { i32::from(d) - 1 } else { i32::from(d) };
    w!(o, "% Numbering");
    w!(o, "\\setcounter{{secnumdepth}}{{{}}}", depth(t.structure.numbered_depth));
    w!(o, "\\setcounter{{tocdepth}}{{{}}}", depth(t.structure.toc_depth));
    if chapters && !t.structure.per_chapter_numbering {
        for counter in ["equation", "figure", "table"] {
            w!(o, "\\counterwithout{{{counter}}}{{chapter}}");
        }
    }
    w!(o);

    // ---- headings
    w!(o, "% Headings");
    w!(o, "\\RequirePackage{{titlesec}}");
    for (style, cmd) in t.headings.levels.iter().zip(cmds) {
        let shape = match style.layout {
            HeadingLayout::Display => "display",
            HeadingLayout::Inline => "hang",
        };
        let fill = match style.text.align {
            texloom_core::Align::Left => "\\filright",
            texloom_core::Align::Center => "\\filcenter",
            texloom_core::Align::Right => "\\filleft",
        };
        let number = format!("\\the{cmd}");
        let mut label = render_placeholders(&style.label, PlaceholderContext { number: Some(&number) });
        let mut before = String::new();
        if style.text.uppercase {
            label = format!("\\MakeUppercase{{{label}}}");
            before.push_str("\\MakeUppercase");
        }
        w!(
            o,
            "\\titleformat{{\\{cmd}}}[{shape}]{{\\normalfont{}{fill}}}{{{label}}}{{{}pt}}{{{before}}}",
            font_commands(&style.text),
            num(style.label_gap_pt)
        );
        w!(o, "\\titlespacing*{{\\{cmd}}}{{0pt}}{{{}pt}}{{{}pt}}", num(style.space_before_pt), num(style.space_after_pt));
    }
    w!(o);

    // ---- metadata fields
    w!(o, "% Metadata fields");
    w!(o, "\\newcommand\\texloomfield[2]{{\\expandafter\\def\\csname tl@f@#1\\endcsname{{#2}}}}");
    w!(o, "\\newcommand\\tl@f[1]{{\\ifcsname tl@f@#1\\endcsname\\csname tl@f@#1\\endcsname\\fi}}");
    w!(o, "\\newcommand\\tl@ifnonempty[2]{{\\ifcsname tl@f@#1\\endcsname#2\\fi}}");
    w!(o, "\\newcommand\\texloomsep{{, }}");
    w!(o);

    // ---- headers and footers
    w!(o, "% Headers and footers");
    w!(o, "\\RequirePackage{{fancyhdr}}");
    let (mark_top, mark_sub) = if chapters { ("chapter", "section") } else { ("section", "subsection") };
    w!(o, "% {{chapter}} and {{section}} placeholders show the plain titles.");
    w!(o, "\\newcommand\\tl@marks{{\\renewcommand\\{mark_top}mark[1]{{\\markboth{{##1}}{{}}}}\\renewcommand\\{mark_sub}mark[1]{{\\markright{{##1}}}}}}");
    let hf = &t.header_footer;
    w!(o, "{}", page_style("texloomfront", &hf.front_matter));
    w!(o, "{}", page_style("texloommain", &hf.main));
    w!(o, "{}", page_style("texloomchapter", &hf.chapter_opening));
    // Chapter-opening pages use "plain": follow the front-matter style before the
    // main text, the chapter-opening style after it.
    w!(o, "\\let\\ps@plain\\ps@texloomchapter");
    w!(o);

    // ---- title page
    w!(o, "% Title page");
    w!(o, "\\newcommand\\tl@titlepage{{%");
    w!(o, "  \\begin{{titlepage}}%");
    w!(o, "  \\renewcommand\\texloomsep{{\\\\}}%");
    // Never hyphenate words on the title page.
    w!(o, "  \\hyphenpenalty=10000\\exhyphenpenalty=10000%");
    w!(o, "  \\begin{{tikzpicture}}[remember picture,overlay]%");
    for item in &t.title_page.items {
        w!(o, "  {}%", title_item(item));
    }
    w!(o, "  \\end{{tikzpicture}}%");
    w!(o, "  \\end{{titlepage}}}}");
    w!(o);

    // ---- front matter & main matter
    let page_numbers = |s: PageNumberStyle| match s {
        PageNumberStyle::Arabic => "arabic",
        PageNumberStyle::LowerRoman => "roman",
        PageNumberStyle::UpperRoman => "Roman",
    };
    let new_page = if t.page.two_sided { "\\cleardoublepage" } else { "\\clearpage" };
    // With chapters, \chapter* starts its own page; without, end each item's page.
    let after_item = if chapters { "" } else { new_page };
    w!(o, "% Front matter: everything before the main text, in template order");
    w!(o, "\\newcommand\\texloomfrontmatter{{%");
    w!(o, "  \\pagenumbering{{{}}}\\let\\ps@plain\\ps@texloomfront\\pagestyle{{texloomfront}}\\tl@marks", page_numbers(t.structure.front_matter_page_numbers));
    for item in &t.front_matter {
        match item {
            FrontMatterItem::TitlePage => w!(o, "  \\tl@titlepage"),
            FrontMatterItem::FieldPage { title, field, in_toc } => {
                let title = escape(title);
                let toc = if *in_toc {
                    format!("\\phantomsection\\addcontentsline{{toc}}{{{mark_top}}}{{{title}}}")
                } else {
                    String::new()
                };
                w!(o, "  \\tl@ifnonempty{{{field}}}{{\\{mark_top}*{{{title}}}{toc}\\tl@f{{{field}}}\\par{after_item}}}%");
            }
            FrontMatterItem::TableOfContents { title } => {
                w!(o, "  \\renewcommand\\contentsname{{{}}}\\tableofcontents{after_item}", escape(title))
            }
            FrontMatterItem::ListOfFigures { title } => {
                w!(o, "  \\renewcommand\\listfigurename{{{}}}\\listoffigures{after_item}", escape(title))
            }
            FrontMatterItem::ListOfTables { title } => {
                w!(o, "  \\renewcommand\\listtablename{{{}}}\\listoftables{after_item}", escape(title))
            }
        }
    }
    w!(o, "}}");
    w!(o, "\\newcommand\\texloommainmatter{{%");
    w!(o, "  {new_page}\\pagenumbering{{{}}}\\let\\ps@plain\\ps@texloomchapter\\pagestyle{{texloommain}}\\tl@marks}}", page_numbers(t.structure.main_page_numbers));
    w!(o, "\\AtBeginDocument{{\\pagestyle{{texloommain}}\\tl@marks}}");
    w!(o);

    // hyperref goes last, as it patches many of the packages above.
    w!(o, "\\RequirePackage[hidelinks]{{hyperref}}");

    if let Some(raw) = t.raw_preamble.as_deref().filter(|r| !r.trim().is_empty()) {
        w!(o);
        w!(o, "% Raw preamble from the template");
        w!(o, "{}", raw.trim_end());
    }
    w!(o, "\\endinput");
    o
}

fn font_line(cmd: &str, choice: &FontChoice) -> Option<String> {
    match choice {
        // fontspec already defaults to Latin Modern.
        FontChoice::Builtin { font: BuiltinFont::LatinModern } => None,
        FontChoice::Builtin { font } => {
            let file = match font {
                BuiltinFont::Termes => "texgyretermes",
                BuiltinFont::Pagella => "texgyrepagella",
                BuiltinFont::Bonum => "texgyrebonum",
                BuiltinFont::Schola => "texgyreschola",
                BuiltinFont::Heros => "texgyreheros",
                BuiltinFont::Adventor => "texgyreadventor",
                BuiltinFont::Cursor => "texgyrecursor",
                BuiltinFont::LatinModern => unreachable!(),
            };
            // Loaded by file name so it works without any fonts installed on the system.
            Some(format!(
                "\\{cmd}{{{file}}}[Extension=.otf,UprightFont=*-regular,BoldFont=*-bold,ItalicFont=*-italic,BoldItalicFont=*-bolditalic]"
            ))
        }
        FontChoice::System { family } => Some(format!("\\{cmd}{{{}}}", escape(family))),
    }
}

fn page_style(name: &str, s: &PageStyle) -> String {
    let ctx = PlaceholderContext { number: None };
    let mut body = String::from("\\fancyhf{}");
    for (pos, text) in [("L", &s.header.left), ("C", &s.header.center), ("R", &s.header.right)] {
        if !text.is_empty() {
            body.push_str(&format!("\\fancyhead[{pos}]{{{}}}", render_placeholders(text, ctx)));
        }
    }
    for (pos, text) in [("L", &s.footer.left), ("C", &s.footer.center), ("R", &s.footer.right)] {
        if !text.is_empty() {
            body.push_str(&format!("\\fancyfoot[{pos}]{{{}}}", render_placeholders(text, ctx)));
        }
    }
    body.push_str(&format!(
        "\\renewcommand\\headrulewidth{{{}pt}}\\renewcommand\\footrulewidth{{{}pt}}",
        num(s.header_rule_pt),
        num(s.footer_rule_pt)
    ));
    format!("\\fancypagestyle{{{name}}}{{{body}}}")
}

fn anchor_name(a: Anchor) -> &'static str {
    match a {
        Anchor::TopLeft => "north west",
        Anchor::Top => "north",
        Anchor::TopRight => "north east",
        Anchor::Left => "west",
        Anchor::Center => "center",
        Anchor::Right => "east",
        Anchor::BottomLeft => "south west",
        Anchor::Bottom => "south",
        Anchor::BottomRight => "south east",
    }
}

/// Position relative to the paper's top-left corner.
fn at(x_mm: f32, y_mm: f32) -> String {
    format!("([xshift={}mm,yshift={}mm]current page.north west)", num(x_mm), num(-y_mm))
}

fn title_item(item: &texloom_core::TitleItem) -> String {
    let anchor = anchor_name(item.anchor);
    match &item.content {
        TitleContent::Text { text, style, width_mm } => {
            let mut content = render_placeholders(text, PlaceholderContext { number: None });
            if style.uppercase {
                content = format!("\\MakeUppercase{{{content}}}");
            }
            let width = width_mm.map(|w| format!(",text width={}mm", num(w))).unwrap_or_default();
            format!(
                "\\node[anchor={anchor},inner sep=0pt,align={}{width},font={{{}}}] at {} {{{content}}};",
                align_name(style.align),
                font_commands(style),
                at(item.x_mm, item.y_mm)
            )
        }
        TitleContent::Image { asset, width_mm } => format!(
            "\\node[anchor={anchor},inner sep=0pt] at {} {{\\includegraphics[width={}mm]{{{asset}}}}};",
            at(item.x_mm, item.y_mm),
            num(*width_mm)
        ),
        TitleContent::Rule { length_mm, thickness_pt } => {
            // The anchor's horizontal part decides where the line starts.
            let shift = match item.anchor {
                Anchor::TopLeft | Anchor::Left | Anchor::BottomLeft => 0.0,
                Anchor::Top | Anchor::Center | Anchor::Bottom => length_mm / 2.0,
                Anchor::TopRight | Anchor::Right | Anchor::BottomRight => *length_mm,
            };
            format!(
                "\\draw[line width={}pt] {} -- ++({}mm,0);",
                num(*thickness_pt),
                at(item.x_mm - shift, item.y_mm),
                num(*length_mm)
            )
        }
    }
}
