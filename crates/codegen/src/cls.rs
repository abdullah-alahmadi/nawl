//! Template → LaTeX class (`.cls`).
//!
//! The class is self-contained and usable outside Texloom: a document sets metadata
//! with `\texloomfield{id}{value}`, then calls `\texloomfrontmatter` and
//! `\texloommainmatter`. Package mapping: geometry (page), fontspec (fonts), setspace
//! (line spacing), titlesec (headings), fancyhdr + lastpage (headers/footers),
//! TikZ overlay (title page), hyperref (links).

use std::fmt::Write;

use crate::Engine;

use texloom_core::{
    Anchor, BibStyle, BuiltinFont, CaptionAlign, CaptionSeparator, CaptionSize, FontChoice, FrontMatterItem, HeadingLayout, LineSpacing, PageNumberStyle,
    PageStyle, Paper, Template, TitleContent, TopLevel,
};

use crate::language::Languages;
use crate::latex::{align_name, escape, font_commands, num, render_placeholders, PlaceholderContext};

/// Heading commands for editor levels 1–4.
pub fn heading_commands(top: TopLevel) -> [&'static str; 4] {
    match top {
        TopLevel::Chapter => ["chapter", "section", "subsection", "subsubsection"],
        TopLevel::Section => ["section", "subsection", "subsubsection", "paragraph"],
    }
}

/// Writes formatted lines into a `String` (writing to a String can't fail).
macro_rules! w {
    ($o:expr) => { $o.push('\n') };
    ($o:expr, $($arg:tt)*) => { writeln!($o, $($arg)*).expect("write to String") };
}

pub fn template_to_cls(t: &Template) -> String {
    template_to_cls_for(t, Engine::Xe)
}

/// The class for a particular engine (fonts differ between pdfLaTeX and the others).
pub fn template_to_cls_for(t: &Template, engine: Engine) -> String {
    if t.kind == texloom_core::DocumentKind::Presentation {
        return crate::presentation::presentation_cls(t);
    }
    if let Some(base) = &t.base {
        return crate::publisher::wrapper_cls(t, base, engine);
    }
    // Fixed texts in another script than the template's language keep their direction.
    let langs = Languages::of_template(t);
    let tx = |s: &str| crate::language::text(s, langs.main, &langs);
    let mut o = String::new();
    let id = &t.meta.id;
    let one_line = |s: &str| s.replace(['\n', '\r'], " ");
    let chapters = t.structure.top_level == TopLevel::Chapter;

    // ---- identification
    w!(o, "% {id}.cls — generated by Texloom from the template \"{}\" (v{}).", one_line(&t.meta.name), one_line(&t.meta.version));
    w!(o, "% Edit the template in Texloom instead of this file: it is regenerated.");
    w!(o, "%");
    w!(o, "% Usage:");
    w!(o, "%   \\documentclass{{{id}}}");
    for f in &t.fields {
        w!(o, "%   \\texloomfield{{{}}}{{...}}   % {}", f.id, one_line(&f.label));
    }
    w!(o, "%   \\begin{{document}}");
    w!(o, "%   \\texloomfrontmatter");
    w!(o, "%   \\texloommainmatter");
    w!(o, "%   ...");
    w!(o, "%   \\end{{document}}");
    w!(o, "% List fields separate entries with \\texloomsep.");
    w!(o, "\\NeedsTeXFormat{{LaTeX2e}}");
    // No "[date version]" text: LaTeX parses its start as a date, and some classes
    // (IEEEtran in journal mode) compare it, failing on anything else.
    w!(o, "\\ProvidesClass{{{id}}}");
    w!(o);

    // ---- base class
    let base = if chapters { "report" } else { "article" };
    let sides = if t.page.two_sided { "twoside" } else { "oneside" };
    let mut extra = if chapters { ",openany" } else { "" }.to_string();
    if t.page.columns == 2 {
        extra.push_str(",twocolumn");
    }
    w!(o, "\\LoadClass[{}pt,{sides}{extra}]{{{base}}}", t.fonts.base_size_pt);
    if t.page.columns == 2 {
        w!(o, "\\setlength\\columnsep{{6mm}}");
    }
    w!(o);

    // ---- page geometry
    let (pw, ph) = t.page.paper.size_mm();
    let paper = match t.page.paper {
        Paper::A4 => "a4paper".to_string(),
        Paper::A5 => "a5paper".to_string(),
        Paper::Letter => "letterpaper".to_string(),
        Paper::Legal => "legalpaper".to_string(),
        Paper::Custom { .. } => format!("paperwidth={}mm,paperheight={}mm", num(pw), num(ph)),
    };
    let m = &t.page.margins;
    w!(o, "% Page");
    w!(
        o,
        "\\RequirePackage[{paper},top={}mm,bottom={}mm,inner={}mm,outer={}mm,bindingoffset={}mm,headheight=15pt]{{geometry}}",
        num(m.top_mm),
        num(m.bottom_mm),
        num(m.inner_mm),
        num(m.outer_mm),
        num(t.page.binding_offset_mm)
    );
    w!(o, "\\RequirePackage{{setspace}}");
    match t.page.line_spacing {
        LineSpacing::Single => w!(o, "\\singlespacing"),
        LineSpacing::OneHalf => w!(o, "\\onehalfspacing"),
        LineSpacing::Double => w!(o, "\\doublespacing"),
        LineSpacing::Custom { stretch } => w!(o, "\\setstretch{{{}}}", num(stretch)),
    }
    // Same space after every period ("Dr. Lopez"), as in modern typography.
    w!(o, "\\frenchspacing");
    w!(o, "\\setlength{{\\parindent}}{{{}mm}}", num(t.page.paragraph.indent_mm));
    w!(o, "\\setlength{{\\parskip}}{{{}pt plus 1pt}}", num(t.page.paragraph.spacing_pt));
    w!(o);

    // ---- fonts
    w!(o, "% Fonts");
    if engine.unicode_fonts() {
        w!(o, "\\RequirePackage{{fontspec}}");
        for (cmd, choice) in [("setmainfont", &t.fonts.main), ("setsansfont", &t.fonts.sans), ("setmonofont", &t.fonts.mono)] {
            if let Some(line) = font_line(cmd, choice) {
                w!(o, "{line}");
            }
        }
    } else {
        // pdfLaTeX: the TeX Gyre fonts as classic font packages; system fonts need
        // XeLaTeX or LuaLaTeX, so they fall back to Latin Modern here.
        w!(o, "\\RequirePackage[T1]{{fontenc}}");
        w!(o, "\\RequirePackage{{lmodern}}");
        for choice in [&t.fonts.main, &t.fonts.sans, &t.fonts.mono] {
            match pdf_font_package(choice) {
                Some(pkg) => w!(o, "\\RequirePackage{{{pkg}}}"),
                None if matches!(choice, FontChoice::System { .. } | FontChoice::Library { .. }) => {
                    w!(o, "% Font files need XeLaTeX or LuaLaTeX (pdfLaTeX can't load them); Latin Modern instead")
                }
                None => {}
            }
        }
        w!(o, "\\RequirePackage{{textcomp}}");
    }
    o.push_str(&style_fonts(t, engine));
    w!(o);

    // ---- packages used by document content
    w!(o, "% Content");
    w!(o, "\\RequirePackage{{amsmath,amssymb}}");
    w!(o, "\\RequirePackage{{graphicx}}");
    w!(o, "\\RequirePackage{{xcolor}}");
    w!(o, "\\RequirePackage{{tikz}}");
    w!(o, "\\RequirePackage[normalem]{{ulem}}");
    w!(o, "\\RequirePackage{{enumitem}}");
    w!(o, "\\RequirePackage{{lastpage}}");
    w!(o, "\\RequirePackage{{tabularx}}");
    // Table cells: ragged (no stretched gaps in narrow columns), a little padding;
    // right-to-left text starts at the right.
    let ragged = if langs.main.rtl() { "raggedleft" } else { "raggedright" };
    w!(o, "\\newcolumntype{{L}}{{>{{\\{ragged}\\arraybackslash}}X}}");
    w!(o, "\\renewcommand\\arraystretch{{1.3}}");
    w!(o);

    // ---- captions
    let c = &t.captions;
    let sep = match c.separator {
        CaptionSeparator::Colon => "colon",
        CaptionSeparator::Period => "period",
        CaptionSeparator::Dash => "endash",
        CaptionSeparator::Newline => "newline",
    };
    let size = match c.size {
        CaptionSize::Footnote => "footnotesize",
        CaptionSize::Small => "small",
        CaptionSize::Normal => "normalsize",
    };
    let justification = match c.align {
        CaptionAlign::Center => "justification=centering",
        CaptionAlign::Left => "justification=raggedright,singlelinecheck=false",
        CaptionAlign::Justified => "justification=justified,singlelinecheck=true",
    };
    let label_font = if c.label_bold { "bf" } else { "normal" };
    w!(o, "% Captions");
    w!(o, "\\RequirePackage{{caption}}");
    w!(o, "\\captionsetup{{labelfont={label_font},labelsep={sep},font={size},{justification}}}");
    w!(o, "\\captionsetup[table]{{position=top}}");
    w!(o, "% A caption outside a float (figures and tables inside columns)");
    w!(o, "\\newcommand\\texloomcaptionof[2]{{\\def\\@captype{{#1}}\\caption{{#2}}}}");
    w!(o, "\\renewcommand\\figurename{{{}}}", tx(&c.figure_label));
    w!(o, "\\renewcommand\\tablename{{{}}}", tx(&c.table_label));
    w!(o);

    // ---- numbering
    let cmds = heading_commands(t.structure.top_level);
    let depth = |d: u8| if chapters { i32::from(d) - 1 } else { i32::from(d) };
    w!(o, "% Numbering");
    w!(o, "\\setcounter{{secnumdepth}}{{{}}}", depth(t.structure.numbered_depth));
    w!(o, "\\setcounter{{tocdepth}}{{{}}}", depth(t.structure.toc_depth));
    if chapters && !t.structure.per_chapter_numbering {
        for counter in ["equation", "figure", "table"] {
            w!(o, "\\counterwithout{{{counter}}}{{chapter}}");
        }
    }
    w!(o);

    // ---- headings
    w!(o, "% Headings");
    w!(o, "\\RequirePackage{{titlesec}}");
    o.push_str(&heading_formats(t, &langs));
    w!(o);

    // ---- metadata fields
    w!(o, "% Metadata fields");
    w!(o, "\\newcommand\\texloomfield[2]{{\\expandafter\\def\\csname tl@f@#1\\endcsname{{#2}}}}");
    w!(o, "\\newcommand\\tl@f[1]{{\\ifcsname tl@f@#1\\endcsname\\csname tl@f@#1\\endcsname\\fi}}");
    w!(o, "\\newcommand\\tl@ifnonempty[2]{{\\ifcsname tl@f@#1\\endcsname#2\\fi}}");
    w!(o, "\\newcommand\\texloomsep{{, }}");
    // Between entries of an English list (an Arabic document's English author names):
    // an English comma, inside the list's one English run.
    w!(o, "\\newcommand\\texloomsepen{{, }}");
    w!(o);

    // ---- headers and footers
    w!(o, "% Headers and footers");
    w!(o, "\\RequirePackage{{fancyhdr}}");
    let (mark_top, mark_sub) = if chapters { ("chapter", "section") } else { ("section", "subsection") };
    w!(o, "% {{chapter}} and {{section}} placeholders show the plain titles.");
    w!(o, "\\newcommand\\tl@marks{{\\renewcommand\\{mark_top}mark[1]{{\\markboth{{##1}}{{}}}}\\renewcommand\\{mark_sub}mark[1]{{\\markright{{##1}}}}}}");
    let hf = &t.header_footer;
    w!(o, "{}", page_style("texloomfront", &hf.front_matter, &langs));
    w!(o, "{}", page_style("texloommain", &hf.main, &langs));
    w!(o, "{}", page_style("texloomchapter", &hf.chapter_opening, &langs));
    // Chapter-opening pages use "plain": follow the front-matter style before the
    // main text, the chapter-opening style after it.
    w!(o, "\\let\\ps@plain\\ps@texloomchapter");
    w!(o);

    // ---- title page
    w!(o, "% Title page");
    w!(o, "\\newcommand\\tl@titlepage{{%");
    match t.title_page.block_height_mm {
        // An article's title block, at the top of the first page's text. A title or
        // author list longer than designed mustn't run into what follows, so the items
        // flow down: across, they keep their exact places; down, each row sits below
        // the real bottom of the row above, at the designed gap. The picture takes up
        // its height, and the text starts below it (at `height` when all fits).
        Some(height) => {
            let left = t.page.margins.inner_mm + t.page.binding_offset_mm;
            let top = t.page.margins.top_mm;
            // Lists (authors) run on in a line, as in articles; title pages stack them.
            let sep = if langs.main.rtl() { "، " } else { ", " };
            w!(o, "  {{\\renewcommand\\texloomsep{{{sep}}}\\hyphenpenalty=10000\\exhyphenpenalty=10000%");
            // Full width, so it sits the same in right-to-left text.
            w!(o, "  \\par\\noindent\\begin{{tikzpicture}}\\path (0,0) -- (\\linewidth,0);%");
            let mut bottom = top;
            for (k, row) in title_rows(&t.title_page.items).iter().enumerate() {
                w!(o, "  \\coordinate (tl@row{k}) at (current bounding box.south -| 0,0);%");
                let above = bottom;
                for item in row {
                    let at = |x: f32, y: f32| format!("([shift={{({}mm,{}mm)}}]tl@row{k})", num(x - left), num(above - y));
                    w!(o, "  {}%", title_item(item, &langs, &at));
                    bottom = bottom.max(item_extent(item).1);
                }
            }
            w!(o, "  \\path (current bounding box.south) -- ++(0,-{}mm);%", num((height - bottom).max(2.0)));
            w!(o, "  \\end{{tikzpicture}}\\par}}}}");
        }
        None => {
            w!(o, "  \\begin{{titlepage}}%");
            w!(o, "  \\renewcommand\\texloomsep{{\\\\}}\\renewcommand\\texloomsepen{{\\\\}}%");
            // Never hyphenate words on the title page.
            w!(o, "  \\hyphenpenalty=10000\\exhyphenpenalty=10000%");
            w!(o, "  \\begin{{tikzpicture}}[remember picture,overlay]%");
            for item in &t.title_page.items {
                w!(o, "  {}%", title_item(item, &langs, &at));
            }
            w!(o, "  \\end{{tikzpicture}}%");
            w!(o, "  \\end{{titlepage}}}}");
        }
    }
    w!(o);

    // ---- front matter & main matter
    let page_numbers = |s: PageNumberStyle| match s {
        PageNumberStyle::Arabic => "arabic",
        PageNumberStyle::LowerRoman => "roman",
        PageNumberStyle::UpperRoman => "Roman",
    };
    let new_page = if t.page.two_sided { "\\cleardoublepage" } else { "\\clearpage" };
    // With chapters, \chapter* starts its own page; without, end each item's page.
    let after_item = if chapters { "" } else { new_page };
    let item_tex = |item: &FrontMatterItem| -> String {
        let mut o = String::new();
        match item {
            FrontMatterItem::TitlePage => w!(o, "  \\tl@titlepage"),
            FrontMatterItem::FieldPage { title, field, in_toc, language, inline } => {
                let title = tx(title);
                let toc = if *in_toc {
                    format!("\\phantomsection\\addcontentsline{{toc}}{{{mark_top}}}{{{title}}}")
                } else {
                    String::new()
                };
                // Under the title (an article's abstract): a section heading on the same
                // page; otherwise a page of its own.
                let (heading, after) = if *inline { ("section", "") } else { (mark_top, after_item) };
                match language.filter(|l| *l != langs.main) {
                    // A page in the other language: its own direction. The contents
                    // entry is made outside, in the document's language, after the page
                    // break (so it has the right page number).
                    Some(other) => {
                        let env = other.environment();
                        let page = if chapters && !*inline { new_page } else { "" };
                        w!(o, "  \\tl@ifnonempty{{{field}}}{{{page}{toc}\\begin{{{env}}}\\{heading}*{{{title}}}\\tl@f{{{field}}}\\par\\end{{{env}}}{after}}}%");
                    }
                    None => w!(o, "  \\tl@ifnonempty{{{field}}}{{\\{heading}*{{{title}}}{toc}\\tl@f{{{field}}}\\par{after}}}%"),
                }
            }
            FrontMatterItem::TableOfContents { title } => {
                w!(o, "  \\renewcommand\\contentsname{{{}}}\\tableofcontents{after_item}", tx(title))
            }
            FrontMatterItem::ListOfFigures { title } => {
                w!(o, "  \\renewcommand\\listfigurename{{{}}}\\listoffigures{after_item}", tx(title))
            }
            FrontMatterItem::FixedPage { title, items, in_toc } => {
                // Like the title page, on a page of its own with the front matter's page
                // style; \null gives the page something to ship besides the overlay.
                let toc = if *in_toc {
                    format!("\\phantomsection\\addcontentsline{{toc}}{{{mark_top}}}{{{}}}", tx(title))
                } else {
                    String::new()
                };
                w!(o, "  \\clearpage{{\\renewcommand\\texloomsep{{\\\\}}\\renewcommand\\texloomsepen{{\\\\}}\\hyphenpenalty=10000\\exhyphenpenalty=10000\\null{toc}%");
                w!(o, "  \\begin{{tikzpicture}}[remember picture,overlay]%");
                for item in items {
                    w!(o, "  {}%", title_item(item, &langs, &at));
                }
                w!(o, "  \\end{{tikzpicture}}\\par}}{new_page}%");
            }
            FrontMatterItem::ListOfTables { title } => {
                w!(o, "  \\renewcommand\\listtablename{{{}}}\\listoftables{after_item}", tx(title))
            }
        }
        o
    };
    // An article's first page: a title block and what is set under it (the abstract).
    // In two columns they span both, in \twocolumn's optional argument. When that is
    // the whole front matter, the main text follows on the same page, numbered from 1.
    let on_first_page = |item: &FrontMatterItem| match item {
        FrontMatterItem::TitlePage => t.title_page.block_height_mm.is_some(),
        FrontMatterItem::FieldPage { inline, .. } => *inline,
        _ => false,
    };
    let head = t.front_matter.iter().take_while(|i| on_first_page(i)).count();
    let continuous = head > 0 && head == t.front_matter.len();
    w!(o, "% Front matter: everything before the main text, in template order");
    w!(o, "\\newcommand\\texloomfrontmatter{{%");
    if continuous {
        w!(o, "  \\pagenumbering{{{}}}\\pagestyle{{texloommain}}\\tl@marks", page_numbers(t.structure.main_page_numbers));
    } else {
        w!(o, "  \\pagenumbering{{{}}}\\let\\ps@plain\\ps@texloomfront\\pagestyle{{texloomfront}}\\tl@marks", page_numbers(t.structure.front_matter_page_numbers));
    }
    let first: String = t.front_matter[..head].iter().map(item_tex).collect();
    if t.page.columns == 2 && head > 0 {
        w!(o, "  \\twocolumn[{{%");
        o.push_str(&first);
        // Space between the spanning block and the columns' first lines.
        w!(o, "  \\par\\vspace{{\\baselineskip}}}}]%");
    } else {
        o.push_str(&first);
    }
    if head > 0 {
        // The first page opens like a chapter (the "plain" style: no running header).
        w!(o, "  \\thispagestyle{{texloomchapter}}%");
    }
    for item in &t.front_matter[head..] {
        o.push_str(&item_tex(item));
    }
    w!(o, "}}");
    w!(o, "\\newcommand\\texloommainmatter{{%");
    if continuous {
        w!(o, "  \\let\\ps@plain\\ps@texloomchapter\\pagestyle{{texloommain}}\\tl@marks}}");
    } else {
        w!(o, "  {new_page}\\pagenumbering{{{}}}\\let\\ps@plain\\ps@texloomchapter\\pagestyle{{texloommain}}\\tl@marks}}", page_numbers(t.structure.main_page_numbers));
    }
    w!(o, "\\AtBeginDocument{{\\pagestyle{{texloommain}}\\tl@marks}}");
    w!(o);

    // ---- bibliography (BibTeX, run automatically by the TeX engine)
    let bib = &t.bibliography;
    let bst = match bib.style {
        BibStyle::Ieee => "IEEEtran",
        BibStyle::Numeric => "plain",
        BibStyle::AuthorYear => "apalike",
    };
    let list_name = if chapters { "bibname" } else { "refname" };
    w!(o, "% Bibliography: refs.bib next to the document");
    if bib.style == BibStyle::AuthorYear {
        w!(o, "\\RequirePackage[round]{{natbib}}");
    }
    let toc = if bib.in_toc {
        format!("\\phantomsection\\addcontentsline{{toc}}{{{mark_top}}}{{{}}}", tx(&bib.title))
    } else {
        String::new()
    };
    let bib_page = if chapters { new_page } else { "" };
    w!(
        o,
        "\\newcommand\\texloombibliography{{{bib_page}{toc}\\renewcommand\\{list_name}{{{}}}\\bibliographystyle{{{bst}}}\\bibliography{{refs}}}}",
        tx(&bib.title)
    );
    w!(o);

    // ---- appendices: lettered, with their own label ("Appendix A")
    w!(o, "% Appendices");
    let top_style = &t.headings.levels[0];
    w!(o, "\\newcommand\\texloomappendix{{{new_page}\\appendix{}}}", title_format(top_style, cmds[0], &t.structure.appendix_label, &langs));
    w!(o);

    // hyperref goes last, as it patches many of the packages above.
    w!(o, "\\RequirePackage[hidelinks]{{hyperref}}");

    if let Some(raw) = t.raw_preamble.as_deref().filter(|r| !r.trim().is_empty()) {
        w!(o);
        w!(o, "% Raw preamble from the template");
        w!(o, "{}", raw.trim_end());
    }
    w!(o, "\\endinput");
    o
}

/// `\titleformat` and `\titlespacing` for every heading level.
pub(crate) fn heading_formats(t: &Template, langs: &Languages) -> String {
    let mut o = String::new();
    for (style, cmd) in t.headings.levels.iter().zip(heading_commands(t.structure.top_level)) {
        o.push_str(&title_format(style, cmd, &style.label, langs));
        o.push('\n');
        o.push_str(&format!("\\titlespacing*{{\\{cmd}}}{{0pt}}{{{}pt}}{{{}pt}}\n", num(style.space_before_pt), num(style.space_after_pt)));
    }
    o
}

/// `\titleformat` for one heading level with the given number label.
fn title_format(style: &texloom_core::HeadingStyle, cmd: &str, label_template: &str, langs: &Languages) -> String {
    let shape = match style.layout {
        HeadingLayout::Display => "display",
        HeadingLayout::Inline => "hang",
    };
    let fill = match style.text.align {
        texloom_core::Align::Left => "\\filright",
        texloom_core::Align::Center => "\\filcenter",
        texloom_core::Align::Right => "\\filleft",
    };
    let number = format!("\\the{cmd}");
    let mut label = render_placeholders(label_template, PlaceholderContext { number: Some(&number), langs: Some(langs) });
    let mut before = String::new();
    if style.text.uppercase {
        label = format!("\\MakeUppercase{{{label}}}");
        before.push_str("\\MakeUppercase");
    }
    let font = font_commands(&style.text);
    // Unnumbered headings (\chapter*): same font, no label line.
    format!(
        "\\titleformat{{\\{cmd}}}[{shape}]{{\\normalfont{font}{fill}}}{{{label}}}{{{}pt}}{{{before}}}\n\\titleformat{{name=\\{cmd},numberless}}[block]{{\\normalfont{font}{fill}}}{{}}{{0pt}}{{{before}}}",
        num(style.label_gap_pt)
    )
}

/// The pdfLaTeX package for a TeX Gyre font (each sets only its own family).
fn pdf_font_package(choice: &FontChoice) -> Option<&'static str> {
    match choice {
        FontChoice::Builtin { font } => match font {
            BuiltinFont::LatinModern => None,
            BuiltinFont::Termes => Some("tgtermes"),
            BuiltinFont::Pagella => Some("tgpagella"),
            BuiltinFont::Bonum => Some("tgbonum"),
            BuiltinFont::Schola => Some("tgschola"),
            BuiltinFont::Heros => Some("tgheros"),
            BuiltinFont::Adventor => Some("tgadventor"),
            BuiltinFont::Cursor => Some("tgcursor"),
            BuiltinFont::Amiri => None,
        },
        FontChoice::System { .. } | FontChoice::Library { .. } => None,
    }
}

fn font_line(cmd: &str, choice: &FontChoice) -> Option<String> {
    match choice {
        // fontspec already defaults to Latin Modern.
        FontChoice::Builtin { font: BuiltinFont::LatinModern } => None,
        // Its own font files come with it (Amiri.fontspec in the TeX distribution).
        FontChoice::Builtin { font: BuiltinFont::Amiri } => Some(format!("\\{cmd}{{Amiri}}")),
        FontChoice::Builtin { font } => {
            let file = gyre_file(*font)?;
            // Loaded by file name so it works without any fonts installed on the system.
            Some(format!(
                "\\{cmd}{{{file}}}[Extension=.otf,UprightFont=*-regular,BoldFont=*-bold,ItalicFont=*-italic,BoldItalicFont=*-bolditalic]"
            ))
        }
        FontChoice::System { family } => Some(format!("\\{cmd}{{{}}}", escape(family))),
        // From Texloom's font library: its files are in the build folder's fonts/.
        FontChoice::Library { id } => {
            let f = texloom_core::fonts::find(id)?;
            Some(format!("\\{cmd}{{{}}}[{}]", f.regular_file(), library_options(f)))
        }
    }
}

/// The fonts of headings and title-page items that have one of their own, each as a
/// family command (`\tlfontcairo`). Arabic templates shape them as Arabic. pdfLaTeX
/// can't load font files: the commands do nothing there.
pub(crate) fn style_fonts(t: &Template, engine: Engine) -> String {
    let mut o = String::new();
    let mut done: Vec<String> = Vec::new();
    let arabic = t.lang().main == texloom_core::Language::Arabic;
    for f in t.all_fonts().into_iter().skip(3 + usize::from(t.fonts.arabic.is_some())) {
        let cmd = crate::latex::style_font_command(f);
        if done.contains(&cmd) {
            continue;
        }
        done.push(cmd.clone());
        if !engine.unicode_fonts() {
            w!(o, "\\providecommand\\{cmd}{{}}% font files need XeLaTeX or LuaLaTeX");
            continue;
        }
        let script = if arabic || matches!(f, FontChoice::Library { .. }) { "Script=Arabic," } else { "" };
        let spec = match f {
            FontChoice::Builtin { font: BuiltinFont::LatinModern } => "{lmroman10}[Extension=.otf,UprightFont=*-regular,BoldFont=*-bold,ItalicFont=*-italic,BoldItalicFont=*-bolditalic]".to_string(),
            FontChoice::Builtin { font: BuiltinFont::Amiri } => format!("[{script}Ligatures=TeX]{{Amiri}}"),
            FontChoice::Builtin { font } => match gyre_file(*font) {
                Some(file) => format!("{{{file}}}[Extension=.otf,UprightFont=*-regular,BoldFont=*-bold,ItalicFont=*-italic,BoldItalicFont=*-bolditalic]"),
                None => continue,
            },
            FontChoice::System { family } => format!("[{script}Ligatures=TeX]{{{}}}", escape(family)),
            FontChoice::Library { id } => match texloom_core::fonts::find(id) {
                Some(lib) => format!("[{script}Ligatures=TeX,{}]{{{}}}", library_options(lib), lib.regular_file()),
                None => continue,
            },
        };
        w!(o, "\\newfontfamily\\{cmd}{spec}");
    }
    if !o.is_empty() {
        o.insert_str(0, "% Fonts of headings and title-page items\n");
    }
    o
}

/// fontspec options that load a library font from the build folder's `fonts/`.
pub(crate) fn library_options(f: &texloom_core::fonts::LibraryFont) -> String {
    match f.bold_file() {
        Some(bold) => format!("Path=fonts/,BoldFont={bold}"),
        // No bold in the family: a slightly emboldened regular, rather than none.
        None => "Path=fonts/,AutoFakeBold=1.5".into(),
    }
}

/// The file name stem of a TeX Gyre font (`texgyretermes`); `None` for the others.
pub(crate) fn gyre_file(font: BuiltinFont) -> Option<&'static str> {
    Some(match font {
        BuiltinFont::Termes => "texgyretermes",
        BuiltinFont::Pagella => "texgyrepagella",
        BuiltinFont::Bonum => "texgyrebonum",
        BuiltinFont::Schola => "texgyreschola",
        BuiltinFont::Heros => "texgyreheros",
        BuiltinFont::Adventor => "texgyreadventor",
        BuiltinFont::Cursor => "texgyrecursor",
        BuiltinFont::LatinModern | BuiltinFont::Amiri => return None,
    })
}

fn page_style(name: &str, s: &PageStyle, langs: &Languages) -> String {
    let ctx = PlaceholderContext { number: None, langs: Some(langs) };
    let mut body = String::from("\\fancyhf{}");
    for (pos, text) in [("L", &s.header.left), ("C", &s.header.center), ("R", &s.header.right)] {
        if !text.is_empty() {
            body.push_str(&format!("\\fancyhead[{pos}]{{{}}}", render_placeholders(text, ctx)));
        }
    }
    for (pos, text) in [("L", &s.footer.left), ("C", &s.footer.center), ("R", &s.footer.right)] {
        if !text.is_empty() {
            body.push_str(&format!("\\fancyfoot[{pos}]{{{}}}", render_placeholders(text, ctx)));
        }
    }
    body.push_str(&format!(
        "\\renewcommand\\headrulewidth{{{}pt}}\\renewcommand\\footrulewidth{{{}pt}}",
        num(s.header_rule_pt),
        num(s.footer_rule_pt)
    ));
    format!("\\fancypagestyle{{{name}}}{{{body}}}")
}

fn anchor_name(a: Anchor) -> &'static str {
    match a {
        Anchor::TopLeft => "north west",
        Anchor::Top => "north",
        Anchor::TopRight => "north east",
        Anchor::Left => "west",
        Anchor::Center => "center",
        Anchor::Right => "east",
        Anchor::BottomLeft => "south west",
        Anchor::Bottom => "south",
        Anchor::BottomRight => "south east",
    }
}

/// Position relative to the paper's top-left corner.
/// An item's designed top and bottom (mm from the paper's top edge), with text one
/// line per line of the item (what a placeholder becomes isn't known here).
fn item_extent(item: &texloom_core::TitleItem) -> (f32, f32) {
    let height = match &item.content {
        TitleContent::Text { text, style, .. } => (text.matches('\n').count() + 1) as f32 * style.size_pt * 1.2 * 25.4 / 72.0,
        // The aspect ratio isn't known here either.
        TitleContent::Image { width_mm, .. } => width_mm * 0.6,
        TitleContent::Rule { thickness_pt, .. } => thickness_pt * 25.4 / 72.0,
    };
    let top = match item.anchor {
        Anchor::TopLeft | Anchor::Top | Anchor::TopRight => item.y_mm,
        Anchor::Left | Anchor::Center | Anchor::Right => item.y_mm - height / 2.0,
        Anchor::BottomLeft | Anchor::Bottom | Anchor::BottomRight => item.y_mm - height,
    };
    (top, top + height)
}

/// Title-block items in rows from top to bottom: items side by side (overlapping
/// in height) share a row.
fn title_rows(items: &[texloom_core::TitleItem]) -> Vec<Vec<&texloom_core::TitleItem>> {
    let mut sorted: Vec<&texloom_core::TitleItem> = items.iter().collect();
    sorted.sort_by(|a, b| item_extent(a).0.total_cmp(&item_extent(b).0));
    let mut rows: Vec<Vec<&texloom_core::TitleItem>> = Vec::new();
    let mut row_bottom = f32::MIN;
    for item in sorted {
        let (top, bottom) = item_extent(item);
        match rows.last_mut() {
            Some(row) if top < row_bottom - 0.5 => row.push(item),
            _ => rows.push(vec![item]),
        }
        row_bottom = if rows.last().is_some_and(|r| r.len() > 1) { row_bottom.max(bottom) } else { bottom };
    }
    rows
}

fn at(x_mm: f32, y_mm: f32) -> String {
    format!("([xshift={}mm,yshift={}mm]current page.north west)", num(x_mm), num(-y_mm))
}

fn title_item(item: &texloom_core::TitleItem, langs: &Languages, at: &dyn Fn(f32, f32) -> String) -> String {
    let anchor = anchor_name(item.anchor);
    match &item.content {
        TitleContent::Text { text, style, width_mm } => {
            let mut content = render_placeholders(text, PlaceholderContext { number: None, langs: Some(langs) });
            if style.uppercase {
                content = format!("\\MakeUppercase{{{content}}}");
            }
            if langs.main.rtl() {
                // TikZ clears \everypar, where bidi starts each paragraph right to
                // left, so a node's text would run left to right ("عليكم السلام").
                content = format!("\\RL{{{content}}}");
            }
            let width = width_mm.map(|w| format!(",text width={}mm", num(w))).unwrap_or_default();
            format!(
                "\\node[anchor={anchor},inner sep=0pt,align={}{width},font={{{}}}] at {} {{{content}}};",
                align_name(style.align),
                font_commands(style),
                at(item.x_mm, item.y_mm)
            )
        }
        TitleContent::Image { asset, width_mm } => format!(
            "\\node[anchor={anchor},inner sep=0pt] at {} {{\\includegraphics[width={}mm]{{{asset}}}}};",
            at(item.x_mm, item.y_mm),
            num(*width_mm)
        ),
        TitleContent::Rule { length_mm, thickness_pt } => {
            // The anchor's horizontal part decides where the line starts.
            let shift = match item.anchor {
                Anchor::TopLeft | Anchor::Left | Anchor::BottomLeft => 0.0,
                Anchor::Top | Anchor::Center | Anchor::Bottom => length_mm / 2.0,
                Anchor::TopRight | Anchor::Right | Anchor::BottomRight => *length_mm,
            };
            format!(
                "\\draw[line width={}pt] {} -- ++({}mm,0);",
                num(*thickness_pt),
                at(item.x_mm - shift, item.y_mm),
                num(*length_mm)
            )
        }
    }
}
