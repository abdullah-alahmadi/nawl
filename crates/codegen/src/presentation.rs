//! Presentations: a beamer class with the template's theme, and the title slide.
//! The slides themselves are written by the body writer (`tex.rs`).

use texloom_core::{Document, FieldKind, FieldValue, FooterStyle, LogoPlacement, PresentationSettings, Template};

use crate::latex::escape;
use crate::publisher::{field_text, is_safe_path, Authors};

/// Images the document's image fields point at (a logo), relative to its folder.
pub fn image_sources(t: &Template, doc: &Document) -> Vec<String> {
    t.fields
        .iter()
        .filter(|f| f.kind == FieldKind::Image)
        .filter_map(|f| match doc.metadata.get(&f.id) {
            Some(FieldValue::Text(p)) if is_safe_path(p.trim()) => Some(p.trim().to_string()),
            _ => None,
        })
        .collect()
}

/// The presentation's logo: the `logo` image field, when it's a usable path.
fn logo(doc: &Document) -> Option<String> {
    match doc.metadata.get("logo") {
        Some(FieldValue::Text(p)) if is_safe_path(p.trim()) => Some(p.trim().to_string()),
        _ => None,
    }
}

/// A footer part: text (escaped) with `{author}`, `{page}`… as beamer's insert commands.
pub fn footer_part(text: &str) -> String {
    let mut out = String::new();
    let mut rest = text;
    while let Some(start) = rest.find('{') {
        out.push_str(&escape(&rest[..start]));
        let after = &rest[start + 1..];
        let cmd = after.find('}').and_then(|end| {
            let name = &after[..end];
            let cmd = match name {
                "author" => "\\insertshortauthor",
                "title" => "\\insertshorttitle",
                "date" => "\\insertshortdate",
                "institute" => "\\insertshortinstitute",
                "section" => "\\insertsection",
                "page" => "\\insertframenumber",
                "pages" => "\\inserttotalframenumber",
                _ => return None,
            };
            Some((cmd, end))
        });
        match cmd {
            Some((cmd, end)) => {
                out.push_str(cmd);
                out.push_str("{}");
                rest = &after[end + 1..];
            }
            None => {
                out.push_str(&escape("{"));
                rest = after;
            }
        }
    }
    out.push_str(&escape(rest));
    out
}

/// Theme, colour and font theme names go into `\usetheme{…}`: letters, digits, '-'.
pub fn safe_name(s: &str) -> bool {
    !s.is_empty() && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '-')
}

/// The generated class: beamer with the template's theme and slide settings.
pub fn presentation_cls(t: &Template) -> String {
    let p = t.presentation.clone().unwrap_or_default();
    let mut o = String::new();
    let one_line = |s: &str| s.replace(['\n', '\r'], " ");
    o.push_str(&format!(
        "% {}.cls — generated by Texloom from the presentation template \"{}\" (v{}).\n",
        t.meta.id,
        one_line(&t.meta.name),
        one_line(&t.meta.version)
    ));
    o.push_str("\\NeedsTeXFormat{LaTeX2e}\n");
    o.push_str(&format!("\\ProvidesClass{{{}}}\n", t.meta.id));
    // Right-to-left slides: beamer-rl (LuaLaTeX only; XeTeX's bidi no longer supports
    // beamer, so lists and alignment would stay left to right).
    let class = if t.lang().main.rtl() { "beamer-rl" } else { "beamer" };
    o.push_str(&format!("\\LoadClass[aspectratio={},{}pt]{{{class}}}\n", p.aspect_ratio.beamer_option(), font_size(&p)));
    if safe_name(&p.theme) {
        o.push_str(&format!("\\usetheme{{{}}}\n", p.theme));
    }
    if safe_name(&p.color_theme) {
        o.push_str(&format!("\\usecolortheme{{{}}}\n", p.color_theme));
    }
    if safe_name(&p.font_theme) {
        o.push_str(&format!("\\usefonttheme{{{}}}\n", p.font_theme));
    }
    // A main colour of the user's own: beamer derives title bars, bullets and
    // blocks from the structure colour.
    if let Some((r, g, b)) = p.accent_color.as_deref().and_then(hex_rgb) {
        o.push_str(&format!("\\usecolortheme[RGB={{{r},{g},{b}}}]{{structure}}\n"));
    }
    match p.footer.style {
        FooterStyle::Theme => {}
        FooterStyle::None => o.push_str("\\setbeamertemplate{footline}{}\n"),
        FooterStyle::Custom => {
            // Three boxes in the theme's head/foot colours, like beamer's infolines.
            let part = |align: &str, skip: &str, colour: &str, text: &str| {
                format!(
                    "\\begin{{beamercolorbox}}[wd=.333333\\paperwidth,ht=2.25ex,dp=1ex,{align}{skip}]{{{colour}}}\\usebeamerfont{{{colour}}}{}\\end{{beamercolorbox}}%\n",
                    footer_part(text)
                )
            };
            o.push_str("% Footer: left, centre and right parts\n");
            o.push_str("\\setbeamertemplate{footline}{%\n\\leavevmode\\hbox{%\n");
            o.push_str(&part("left", ",leftskip=1em", "author in head/foot", &p.footer.left));
            o.push_str(&part("center", "", "title in head/foot", &p.footer.center));
            o.push_str(&part("right", ",rightskip=1em", "date in head/foot", &p.footer.right));
            o.push_str("}\\vskip0pt}\n");
        }
    }
    if !p.navigation_symbols {
        o.push_str("\\setbeamertemplate{navigation symbols}{}\n");
    }
    // Figures and tables on slides: "Figure 1:" like the PDF articles.
    o.push_str("\\setbeamertemplate{caption}[numbered]\n");
    // The references run over several slides without "I, II…" after the title.
    o.push_str("\\setbeamertemplate{frametitle continuation}{}\n");
    o.push('\n');
    o.push_str("% Packages Texloom documents use (beamer loads graphicx, hyperref, amssymb)\n");
    o.push_str("\\RequirePackage{amsmath}\n");
    o.push_str("\\RequirePackage{tabularx}\n");
    o.push_str("\\newcolumntype{L}{>{\\raggedright\\arraybackslash}X}\n");
    o.push_str("\\RequirePackage[normalem]{ulem}\n\n");
    o.push_str("% Metadata fields\n");
    o.push_str("\\newcommand\\texloomfield[2]{\\expandafter\\def\\csname tl@f@#1\\endcsname{#2}}\n");
    o.push_str("\\newcommand\\tl@f[1]{\\ifcsname tl@f@#1\\endcsname\\csname tl@f@#1\\endcsname\\fi}\n");
    o.push_str("\\newcommand\\texloomsep{, }\n\n");
    o.push_str("% Bibliography (refs.bib next to the document), on its own slides\n");
    o.push_str("\\newcommand\\texloombibliography{\\bibliographystyle{plain}\\bibliography{refs}}\n");
    if p.section_slides {
        o.push_str("\n% An outline slide at the start of each section\n");
        let outline = crate::strings::words(t.lang().main).outline;
        o.push_str(&format!("\\AtBeginSection[]{{\\begin{{frame}}{{{outline}}}\\tableofcontents[currentsection]\\end{{frame}}}}\n"));
    }
    if let Some(raw) = t.raw_preamble.as_deref().filter(|r| !r.trim().is_empty()) {
        o.push_str("\n% Raw preamble from the template\n");
        o.push_str(raw.trim_end());
        o.push('\n');
    }
    o.push_str("\\endinput\n");
    o
}

/// `#rrggbb` → (r, g, b).
fn hex_rgb(s: &str) -> Option<(u8, u8, u8)> {
    let h = s.strip_prefix('#').filter(|h| h.len() == 6)?;
    let n = |i: usize| u8::from_str_radix(&h[i..i + 2], 16).ok();
    Some((n(0)?, n(2)?, n(4)?))
}

/// Beamer's font size options (8–20 pt); anything else goes to the nearest one.
fn font_size(p: &PresentationSettings) -> u8 {
    const SIZES: [u8; 8] = [8, 9, 10, 11, 12, 14, 17, 20];
    *SIZES.iter().min_by_key(|s| (i16::from(**s) - i16::from(p.font_size_pt)).abs()).unwrap_or(&11)
}

/// `\title`, `\author`… from the document's fields, then the title slide and the
/// optional outline slide.
pub fn title_slides(t: &Template, doc: &Document) -> String {
    let p = t.presentation.clone().unwrap_or_default();
    let mut o = String::new();
    let title = field_text(doc, t, "title");
    let subtitle = field_text(doc, t, "subtitle");
    let au = Authors::new(doc);
    let names: Vec<String> = au.list.iter().map(|a| escape(&a.name)).filter(|n| !n.is_empty()).collect();
    let institute = match field_text(doc, t, "institute") {
        s if !s.is_empty() => s,
        _ => au.affiliations.iter().map(|a| escape(a)).collect::<Vec<_>>().join(" \\and "),
    };
    let date = field_text(doc, t, "date");
    let short = field_text(doc, t, "short_title");
    if short.is_empty() {
        o.push_str(&format!("\\title{{{title}}}\n"));
    } else {
        // The footer and headers use the short title.
        o.push_str(&format!("\\title[{short}]{{{title}}}\n"));
    }
    if !subtitle.is_empty() {
        o.push_str(&format!("\\subtitle{{{subtitle}}}\n"));
    }
    o.push_str(&format!("\\author{{{}}}\n", names.join(" \\and ")));
    if !institute.is_empty() {
        o.push_str(&format!("\\institute{{{institute}}}\n"));
    }
    o.push_str(&format!("\\date{{{}}}\n", if date.is_empty() { "\\today".to_string() } else { date }));
    if let Some(logo) = logo(doc).filter(|_| p.logo != LogoPlacement::Off) {
        o.push_str(&format!("\\titlegraphic{{\\includegraphics[height=1.4cm,keepaspectratio]{{{logo}}}}}\n"));
        if p.logo == LogoPlacement::EverySlide {
            o.push_str(&format!("\\logo{{\\includegraphics[height=0.7cm,keepaspectratio]{{{logo}}}}}\n"));
        }
    }
    o.push_str("\n\\begin{document}\n\n");
    if !title.is_empty() {
        o.push_str("\\begin{frame}\n\\titlepage\n\\end{frame}\n\n");
    }
    if p.outline {
        let outline = crate::strings::words(t.lang().main).outline;
        o.push_str(&format!("\\begin{{frame}}{{{outline}}}\n\\tableofcontents\n\\end{{frame}}\n\n"));
    }
    o
}
